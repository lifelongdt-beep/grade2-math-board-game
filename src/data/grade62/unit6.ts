const 전개도: G5Family = {
  id: 'net',
  make: (seed, lv) => {
    const next = 고르개(seed);
    const r = 사이(next, 2, 10);
    const h = 사이(next, 3, 20);
    const kind = next(lv === '하' ? 2 : 3);
    if (kind === 0) {
      const v = 2 * r * 3140;
      return {
        prompt: `밑면의 반지름이 ${r} cm, 높이가 ${h} cm인 원기둥의 전개도에서 옆면의 가로는 몇 cm일까요? (원주율: 3.14)`,
        answer: `${소수(v)} cm`,
        wrongs: [소수(r * 3140), 소수(r * r * 3140), `${h}`, 소수(4 * r * 3140)].filter((x, i, xs) => x !== 소수(v) && xs.indexOf(x) === i).slice(0, 3).map((x) => `${x} cm`),
        tag: 'solid',
        strategy: '원기둥 전개도의 옆면 가로',
        hint: '옆면의 가로는 밑면의 둘레(원주)와 같아요.',
        steps: [`밑면의 원주는 ${2 * r}×3.14=${소수(v)}이므로 ${소수(v)} cm입니다.`],
        misconceptionTip: '옆면의 가로는 밑면의 지름이 아니라 원주예요.',
      };
    }
    if (kind === 1) {
      return {
        prompt: `밑면의 반지름이 ${r} cm, 높이가 ${h} cm인 원기둥의 전개도에서 옆면의 세로는 몇 cm일까요?`,
        answer: `${h} cm`,
        wrongs: [...new Set([r, 2 * r, h + r, h * 2])].filter((x) => x !== h).slice(0, 3).map((x) => `${x} cm`),
        tag: 'solid',
        strategy: '원기둥 전개도의 옆면 세로',
        hint: '옆면의 세로는 원기둥의 높이와 같아요.',
        steps: [`옆면의 세로는 높이와 같으므로 ${h} cm입니다.`],
      };
    }
    return {
      prompt: '원기둥의 전개도에서 옆면은 어떤 모양일까요?',
      answer: '직사각형',
      wrongs: ['원', '삼각형', '부채꼴'],
      tag: 'solid',
      strategy: '원기둥의 전개도',
      hint: '원기둥의 옆면을 잘라 펼쳐 보세요.',
      steps: ['원기둥의 전개도에서 밑면은 원 2개, 옆면은 직사각형입니다.'],
    };
  },
};

const 원기둥앞: G5Family = {
  id: 'cylinder-front',
  make: (seed) => {
    const next = 고르개(seed);
    const r = 사이(next, 2, 12);
    const h = 사이(next, 3, 20);
    if (h === 2 * r) return null;
    const 둘레 = next(2) === 0;
    const v = 둘레 ? 2 * (2 * r + h) : 2 * r;
    return {
      prompt: `밑면의 반지름이 ${r} cm, 높이가 ${h} cm인 원기둥을 앞에서 본 모양은 직사각형입니다. 이 직사각형의 ${둘레 ? '네 변의 길이의 합' : '가로'}은(는) 몇 cm일까요?`,
      answer: `${v} cm`,
      wrongs: [...new Set(둘레 ? [2 * (r + h), 2 * r + h, 4 * r + h * 4] : [r, h, 4 * r])].filter((x) => x !== v).slice(0, 3).map((x) => `${x} cm`),
      tag: 'solid',
      strategy: '원기둥을 앞에서 본 모양',
      hint: '앞에서 본 직사각형의 가로는 밑면의 지름, 세로는 높이예요.',
      steps: 둘레 ? [`가로는 지름 ${2 * r} cm, 세로는 높이 ${h} cm입니다.`, `(${2 * r}+${h})×2=${v}이므로 ${v} cm입니다.`] : [`가로는 밑면의 지름이므로 ${r}×2=${2 * r} cm입니다.`],
      misconceptionTip: '가로는 반지름이 아니라 지름이에요.',
    };
  },
};

const 원뿔길이: G5Family = {
  id: 'cone',
  make: (seed) => {
    const next = 고르개(seed);
    // 직각삼각형의 세 변: (3,4,5)의 배수
    const k = 사이(next, 1, 4);
    const [r, h, l] = [3 * k, 4 * k, 5 * k];
    const kind = next(3);
    const 묻는 = (['밑면의 지름', '높이', '모선의 길이'] as const)[kind];
    const v = kind === 0 ? 2 * r : kind === 1 ? h : l;
    return {
      prompt: `원뿔에서 원뿔의 꼭짓점과 밑면의 둘레의 한 점을 이은 선분은 ${l} cm, 원뿔의 꼭짓점에서 밑면에 수직인 선분은 ${h} cm, 밑면의 반지름은 ${r} cm입니다. 이 원뿔의 ${묻는}은(는) 몇 cm일까요?`,
      answer: `${v} cm`,
      wrongs: [...new Set([r, h, l, 2 * r, r + h])].filter((x) => x !== v).slice(0, 3).map((x) => `${x} cm`),
      tag: 'solid',
      strategy: '원뿔의 구성 요소',
      hint: '높이는 꼭짓점에서 밑면에 수직인 선분, 모선은 꼭짓점과 밑면 둘레를 이은 선분이에요.',
      steps: [kind === 0 ? `지름은 반지름의 2배이므로 ${r}×2=${2 * r} cm입니다.` : kind === 1 ? `원뿔의 꼭짓점에서 밑면에 수직인 선분의 길이가 높이이므로 ${h} cm입니다.` : `원뿔의 꼭짓점과 밑면의 둘레의 한 점을 이은 선분이 모선이므로 ${l} cm입니다.`],
    };
  },
};

