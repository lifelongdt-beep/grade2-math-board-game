const 구지름: G5Family = {
  id: 'sphere',
  make: (seed) => {
    const next = 고르개(seed);
    const r = 사이(next, 2, 15);
    const 반 = next(2) === 0;
    return 반
      ? {
          prompt: `지름이 ${2 * r} cm인 구의 반지름은 몇 cm일까요?`,
          answer: `${r} cm`,
          wrongs: [2 * r, 4 * r, r + 1].map((x) => `${x} cm`),
          tag: 'solid',
          strategy: '구의 반지름',
          hint: '구의 반지름은 지름의 절반이에요.',
          steps: [`${2 * r}÷2=${r}이므로 ${r} cm입니다.`],
        }
      : {
          prompt: `반원 모양의 종이를 지름을 기준으로 한 바퀴 돌려 구를 만들었습니다. 반원의 지름이 ${2 * r} cm일 때 구의 반지름은 몇 cm일까요?`,
          answer: `${r} cm`,
          wrongs: [2 * r, 4 * r, r + 2].map((x) => `${x} cm`),
          tag: 'solid',
          strategy: '돌려 만든 구의 반지름',
          hint: '반원의 반지름이 구의 반지름이 돼요.',
          steps: [`반원의 반지름은 ${2 * r}÷2=${r}이므로 구의 반지름은 ${r} cm입니다.`],
        };
  },
};

