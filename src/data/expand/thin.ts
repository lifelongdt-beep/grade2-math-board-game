const 글 = (x: number) => String(Math.round(x * 1000) / 1000);

/** 답이 소수일 수 있는 문항입니다. 보기는 답과 다르고 서로 다른 것만 씁니다. */
const 소수문항 = (결: 0 | 1 | 2, prompt: string, 답: number, 후보: number[], 단위: string, o: Pick<G5Spec, 'tag' | 'strategy' | 'hint' | 'steps'>): G5Spec | null => {
  const 답글 = `${글(답)}${단위}`;
  const wrongs = [...new Set(후보.filter((x) => x > 0).map((x) => `${글(x)}${단위}`))].filter((w) => w !== 답글).slice(0, 3);
  if (wrongs.length < 3) return null;
  return 결로(결, { prompt, answer: 답글, wrongs, ...o });
};

