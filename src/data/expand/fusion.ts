// 융합 문항: 그 차시의 개념에 앞에서 배운 개념을 함께 써야 풀리는 상 문항
// ────────────────────────────────────────────────────────────────────
// 응용력은 한 차시의 셈을 되풀이해서가 아니라, 새로 배운 것을 앞에서 배운
// 것과 이어 쓸 때 자랍니다. 그래서 문항마다 '이 차시의 개념 + 앞 단원·앞 학년의
// 개념'을 하나씩 짝지었습니다(예: 곱셈구구 + 길이, 나눗셈 + 시간, 각도 + 시각).
// 앞 개념은 그 차시보다 먼저 배운 것만 씁니다. 결은 모두 2(사고)라 상에서만 나옵니다.
// 풀이 걸음은 두 개념을 차례로 쓰도록 둘로 나누어 적습니다.
// ════════════════════════════════════════════════════════════════════

/** 융합 문항은 한 판(서른 문항)에 여섯 문항까지만 냅니다. 그 차시의 개념을 익히는 문항이 먼저입니다. */
const 뭉치 = (...a: Parameters<typeof 그냥뭉치>): G5Family => ({ ...그냥뭉치(...a), 최대: 6 });

const 글 = (x: number) => String(Math.round(x * 1000) / 1000);
const 시각글 = (h: number, m: number) => (m ? `${h}시 ${m}분` : `${h}시`);
const 분글 = (분: number) => (분 >= 60 ? `${Math.floor(분 / 60)}시간${분 % 60 ? ` ${분 % 60}분` : ''}` : `${분}분`);
const 엠글 = (cm: number) => (cm >= 100 ? `${Math.floor(cm / 100)} m${cm % 100 ? ` ${cm % 100} cm` : ''}` : `${cm} cm`);
const 공약 = (a: number, b: number): number => (b ? 공약(b, a % b) : a);

/** 답이 글(몇 시 몇 분, 몇 m 몇 cm …)인 융합 문항입니다. */
const 글융합 = (prompt: string, answer: string, 후보: string[], o: Pick<G5Spec, 'tag' | 'strategy' | 'hint' | 'steps'>): G5Spec | null => {
  const wrongs = 글오답(answer, 후보.filter((w) => w && !/^-|NaN|undefined|^0 |^0$/.test(w)));
  return wrongs.length < 3 ? null : 결로(2, { prompt, answer, wrongs, ...o });
};
const 수융합 = (prompt: string, 답: number, 후보: number[], o: { 단위?: string; tag: G5Spec['tag']; strategy: string; hint: string; steps: string[]; 빼기?: boolean }) =>
  수문항(2, prompt, 답, 후보, { ...o, 아래: 1 });

