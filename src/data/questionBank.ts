//   vars     쓸 수를 어떻게 고를지. {from,to}는 그 사이에서 고르고,
//            {calc}는 이미 정한 수로 계산합니다(+ - × 만 씁니다)
//   prompt   문제. 중괄호 안에 변수나 계산을 씁니다. 예: {a + b}
//
// 차시가 다루는 가장 큰 수를 넘는 값이 하나라도 나오면 그 문항은
// 만들어지지 않습니다. 범위를 일일이 확인하지 않아도 됩니다.
