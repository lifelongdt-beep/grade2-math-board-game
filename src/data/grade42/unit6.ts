// ── 정다각형 ────────────────────────────────────────────────────────
const 정다각형둘레: G5Family = {
  id: 'regular-perimeter',
  make: (seed, lv) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, lv === '하' ? 6 : 8);
    const s = 사이(next, 2, 12);
    const 거꾸로 = lv !== '하' && next(2) === 0;
    if (거꾸로) {
      return {
        prompt: `모든 변의 길이의 합이 ${n * s} cm인 ${정이름(n)}의 한 변은 몇 cm일까요?`,
        answer: `${s} cm`,
        wrongs: [...new Set([n * s - n, Math.max(1, Math.floor((n * s) / (n + 1))), Math.floor((n * s) / (n - 1)), s + 1])].filter((x) => x > 0 && x !== s).slice(0, 3).map((x) => `${x} cm`),
        tag: 'shape',
        strategy: '정다각형의 한 변의 길이',
        hint: `${정이름(n)}은(는) 변이 ${n}개이고 길이가 모두 같아요.`,
        steps: [`${n * s}÷${n}=${s}이므로 ${s} cm입니다.`],
        visual: { kind: 'figure-set', label: 정이름(n), items: [{ shape: '사각형', points: 정다각형(n) }] },
      };
    }
    return {
      prompt: `한 변이 ${s} cm인 ${정이름(n)}의 모든 변의 길이의 합은 몇 cm일까요?`,
      answer: `${n * s} cm`,
      wrongs: [...new Set([(n - 1) * s, (n + 1) * s, s + n, 4 * s])].filter((x) => x !== n * s).slice(0, 3).map((x) => `${x} cm`),
      tag: 'shape',
      strategy: '정다각형의 둘레',
      hint: `${정이름(n)}의 변은 몇 개인지 세어 보세요.`,
      steps: [`${정이름(n)}은(는) 변이 ${n}개입니다.`, `${s}×${n}=${n * s}이므로 ${n * s} cm입니다.`],
      visual: { kind: 'figure-set', label: 정이름(n), items: [{ shape: '사각형', points: 정다각형(n) }] },
    };
  },
};

