// ════════════════════════════════════════════════════════════════════
// 4-2 6단원 다각형
// ────────────────────────────────────────────────────────────────────
// 지도서 차시 차례: 단원 도입 / 다각형 / 정다각형 / 대각선 / 모양 만들기 /
// 모양 채우기
//
// 지도서가 못박은 것:
//   · 다각형은 선분으로만 둘러싸인 도형입니다. 변의 수에 따라 오각형,
//     육각형 … 이라고 부릅니다. 볼록다각형만 다룹니다.
//   · 정다각형은 변의 길이가 모두 같고, 각의 크기가 모두 같은 다각형입니다.
//     변의 길이만 같거나 각의 크기만 같으면 정다각형이 아닙니다.
//   · 대각선은 서로 이웃하지 않는 두 꼭짓점을 이은 선분입니다. 삼각형에는
//     대각선이 없습니다.
//   · 모양 만들기·채우기는 모양 조각(정삼각형, 사다리꼴, 마름모,
//     정육각형 …)으로 합니다.
//   · 사각형 사이의 포함 관계는 다루지 않으므로 대각선의 성질을 묻는
//     문항의 보기에 정사각형을 넣지 않습니다.
// ════════════════════════════════════════════════════════════════════

const 이름 = ['', '', '', '삼각형', '사각형', '오각형', '육각형', '칠각형', '팔각형', '구각형', '십각형'];
const 정이름 = (n: number) => `정${이름[n]}`;
const 대각선수 = (n: number) => (n * (n - 3)) / 2;

const 다각형이름: G5Family = {
  id: 'name',
  make: (seed, lv) => {
    const next = 고르개(seed);
    const n = 사이(next, 5, lv === '하' ? 6 : 8);
    return {
      prompt: '그림의 다각형의 이름은 무엇일까요?',
      answer: 이름[n],
      wrongs: [이름[n - 1], 이름[n + 1], 이름[n + 2]],
      tag: 'shape',
      strategy: '변의 수로 다각형 이름 알기',
      hint: '변(또는 꼭짓점)이 몇 개인지 세어 보세요.',
      steps: [`변이 ${n}개이므로 ${이름[n]}입니다.`],
      visual: { kind: 'figure-set', label: '다각형', items: [{ shape: '사각형', points: 고르지않은다각형(n, next) }] },
    };
  },
};

