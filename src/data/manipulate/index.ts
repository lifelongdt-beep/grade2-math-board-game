/** 이 차시·수준에서 만들 수 있는 조작 문항을 n개까지 만듭니다. */
export const 조작문항들 = (lesson: Lesson, difficulty: Difficulty, n: number, 씨앗 = 0): Question[] => {
  const 갈래 = 조작표[`${lesson.semester} ${lesson.unitNo}-${lesson.lessonNo}`]?.[difficulty] ?? [];
  if (!갈래.length || n <= 0) return [];
  const out: Question[] = [];
  const 본글 = new Set<string>();
  let seed = 1 + 씨앗;
  // 칸마다 갈래를 차례로 돌려 씁니다. 한 갈래가 문항을 못 만들면(조건이
  // 안 맞는 씨앗) 같은 갈래로 씨앗만 바꾸어 다시 해 보고, 그래도 안 되면
  // 다음 갈래로 넘깁니다. 씨앗과 갈래를 함께 돌리면 한 갈래만 계속 뽑힐 수 있습니다.
  for (let k = 0; out.length < n && k < n * 3; k += 1) {
    for (let 차례 = 0; 차례 < 갈래.length; 차례 += 1) {
      const g = 갈래[(k + 차례) % 갈래.length];
      let 만듦: Question | null = null;
      for (let 시도 = 0; 시도 < 60 && !만듦; 시도 += 1, seed += 1) {
        const t = g.make(seed * 7919 + difficulty.charCodeAt(0));
        if (!t) continue;
        const q = 조작문항(lesson, difficulty, g.id, seed, t);
        // 같은 문항이 되풀이되지 않게 글과 조작 내용을 함께 봅니다.
        const 열쇠 = `${q.prompt}|${JSON.stringify(q.manipulate)}`;
        if (본글.has(열쇠)) continue;
        본글.add(열쇠);
        만듦 = q;
      }
      if (만듦) { out.push(만듦); break; }
    }
  }
  return out;
};

/**
 * 고르는 문항 사이에 조작 문항을 끼웁니다. 문항 수는 그대로 두고 셋에
 * 하나쯤을 바꿉니다. 조작 문항이 없는 차시는 그대로 돌려줍니다.
 */
export const 조작섞기 = (lesson: Lesson, difficulty: Difficulty, questions: Question[]): Question[] => {
  if (!questions.length) return questions;
  const 몫 = Math.max(1, Math.round(questions.length / 3));
  const 조작 = 조작문항들(lesson, difficulty, 몫);
  if (!조작.length) return questions;
  const out = [...questions];
  조작.forEach((q, k) => {
    const at = Math.min(out.length - 1, 1 + k * 3);
    out[at] = q;
  });
  return out;
};
