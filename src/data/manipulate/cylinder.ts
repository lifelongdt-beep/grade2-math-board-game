import { 고르개, 사이, type 조작갈래 } from './common';

// ════════════════════════════════════════════════════════════════════
// 원기둥의 전개도(6-2 6단원)
// ────────────────────────────────────────────────────────────────────
// 원기둥의 전개도는 옆면 직사각형 하나와 밑면 원 두 개입니다.
//   · 다른 밑면을 붙일 자리 고르기(옆면의 다른 쪽)
//   · 옆면의 가로·세로를 끌어 맞추기: 가로는 밑면의 둘레(원주), 세로는 높이
// ════════════════════════════════════════════════════════════════════

export const 원기둥밑면붙이기: 조작갈래 = {
  id: 'cyl-base',
  make: (seed) => {
    const next = 고르개(seed);
    const side = next(2) ? 'top' : 'bottom';
    const slots = 3;
    const pos = next(slots);
    return {
      prompt: '원기둥의 전개도를 만들려고 합니다. 밑면 하나가 옆면에 붙어 있습니다. 다른 밑면을 붙일 자리를 눌러 보세요.',
      answer: `옆면의 ${side === 'top' ? '아래쪽' : '위쪽'}에 밑면을 붙임`,
      manipulate: { kind: 'cylinder-net', mode: 'base', r: 2, h: 5, pi: 3, slots, bases: [{ pos, side }], step: 1 },
      tag: 'solid',
      strategy: '원기둥의 두 밑면이 서로 마주 보게 붙이기',
      hint: '옆면을 둥글게 말아 세우면 위와 아래가 열려 있어요. 이미 붙은 밑면이 한쪽을 덮으니, 다른 밑면은 반대쪽을 덮어야 해요.',
      steps: ['원기둥은 밑면이 2개이고, 두 밑면은 서로 평행하고 합동입니다.', '옆면을 둥글게 말면 한 밑면은 위를, 다른 밑면은 아래를 덮습니다.', `그러므로 다른 밑면은 옆면의 ${side === 'top' ? '아래쪽' : '위쪽'}에 붙여야 합니다.`],
      concept: '원기둥의 전개도는 옆면인 직사각형 하나와, 옆면의 위·아래에 하나씩 붙은 밑면인 원 2개로 되어 있습니다.',
      misconception: '두 원을 같은 쪽에 붙이면 접었을 때 겹칩니다.',
      결: 1,
    };
  },
};

/** 옆면의 가로(원주)와 세로(높이)를 끌어 맞춥니다. 지름으로 주면 한 번 더 생각해야 합니다. */
export const 옆면크기맞추기 = (원주율: 3 | 3.1, 지름으로: boolean): 조작갈래 => ({
  id: `cyl-size-${원주율}-${지름으로 ? 'd' : 'r'}`,
  make: (seed) => {
    const next = 고르개(seed);
    const r = 사이(next, 1, 4);
    const h = 사이(next, 3, 8);
    const 가로 = Math.round(2 * r * 원주율 * 100) / 100;
    const 말 = 지름으로 ? `밑면의 지름이 ${2 * r} cm` : `밑면의 반지름이 ${r} cm`;
    return {
      prompt: `${말}, 높이가 ${h} cm인 원기둥의 전개도를 그리려고 합니다. 옆면의 오른쪽 변과 아래쪽 변을 끌어 옆면의 크기를 알맞게 맞추어 보세요. (원주율: ${원주율})`,
      answer: `가로 ${가로} cm, 세로 ${h} cm`,
      manipulate: { kind: 'cylinder-net', mode: 'size', r, h, pi: 원주율, slots: 1, bases: [], step: 원주율 === 3 ? 1 : 0.1 },
      tag: 'solid',
      strategy: '옆면의 가로는 원주, 세로는 높이로 맞추기',
      hint: '옆면은 밑면의 둘레를 한 바퀴 감싸요. 옆면의 가로는 밑면의 둘레(원주), 세로는 원기둥의 높이예요.',
      steps: [
        '옆면을 둥글게 말면 옆면의 가로가 밑면의 둘레에 꼭 맞습니다.',
        지름으로 ? `원주는 (지름)×(원주율)이므로 ${2 * r}×${원주율}=${가로}(cm)입니다.` : `원주는 (지름)×(원주율)=(반지름)×2×(원주율)이므로 ${r}×2×${원주율}=${가로}(cm)입니다.`,
        `그러므로 옆면은 가로 ${가로} cm, 세로(높이) ${h} cm인 직사각형입니다.`,
      ],
      concept: '원기둥의 전개도에서 옆면의 가로는 밑면의 둘레와 같고, 세로는 원기둥의 높이와 같습니다.',
      misconception: '옆면의 가로를 밑면의 지름이나 반지름과 같다고 생각하기 쉽습니다.',
      결: 지름으로 ? 2 : 1,
    };
  },
});
