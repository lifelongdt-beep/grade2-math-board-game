  const 답글 = o.답글 ?? 글;
  const labels = Array.from({ length: o.줄.칸 + 1 }, (_, k) => k).filter((k) => k % o.줄.간격 === 0 || k === o.줄.칸).map((k) => ({ at: k, text: 글(값(o.줄, k)) }));
  const 목록 = 맞는.map((k) => 답글(값(o.줄, k)));
