const 틈 = 1e-5;
const 고른 = <T,>(items: T[], next: 다음) => items[next(items.length)];

/** 수직선: 시작 값에서 단위씩 칸만큼. 이름은 간격 칸마다 붙입니다. */
interface 줄 { 시작: number; 칸: number; 단위: number; 간격: number; 글?: (v: number) => string }
