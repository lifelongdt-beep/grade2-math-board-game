const 틀린점 = (m: { target: number; ticks: number }, 값: number, 단위: number, 틀린: [number, string][]) => 틀린
  .map(([v, 말]) => ({ at: m.target + (v - 값) / 단위, 말 }))
  .filter(({ at }) => Number.isInteger(at) && at >= 0 && at <= m.ticks && at !== m.target)
  .map(({ at, 말 }) => ({ state: { kind: 'number-line' as const, at }, 말 }));

