const 수글 = (v: number) => String(Number(v.toFixed(4)));

/** 값 v(u의 배수)를 가운데 둔 30칸 수직선. 큰 눈금은 10칸마다입니다. */
const 창 = (v: number, u: number) => {
  const k = Math.round(v / u);
  const 시작 = Math.max(0, Math.floor(k / 10) * 10 - 10);
  return { kind: 'number-line' as const, ticks: 30, labels: [0, 10, 20, 30].map((t) => ({ at: t, text: 수글((시작 + t) * u) })), target: k - 시작, minor: 10 };
};
