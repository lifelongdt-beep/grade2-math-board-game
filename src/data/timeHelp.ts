/** 갈래 공통 힌트 대신, 문제가 다루는 것에 맞춘 힌트입니다. 답을 말하는 것은 고르지 않습니다. */
const 주제힌트 = (p: string, 시계있음: boolean): string[] => {
  const 후보: string[] = [];
  if (/잘못|틀리게/.test(p)) 후보.push("짧은바늘은 '시', 긴바늘은 '분'을 나타내요. 잘못 읽은 시각에서 어느 바늘을 무엇으로 읽었는지 하나씩 견주어 보세요.");
  if (/하루/.test(p) && /남은/.test(p)) 후보.push('하루가 몇 시간인지 먼저 떠올리고, 그 시간에서 지난 시간을 빼 보세요.');
  if (/걸린 시간/.test(p)) 후보.push('걸린 시간은 시작한 때부터 마친 때까지 흐른 시간이에요. 두 시각을 시간 띠에 표시하고, 정각에서 끊어 그 사이를 세어 보세요.');
  if (/분 전/.test(p)) 후보.push('몇 시 몇 분 전은 다음 정각까지 몇 분이 남았는지로 읽어요. 긴바늘이 12까지 가려면 몇 분이 남았는지 보세요.');
  if (/오전|오후|낮 12시|밤 12시|하루/.test(p)) 후보.push('낮 12시를 기준으로 그 전은 오전, 그 뒤는 오후예요. 하루는 오전과 오후를 합한 시간이에요.', '밤 12시부터 낮 12시까지가 오전, 낮 12시부터 밤 12시까지가 오후예요.');
  if (/1시간|60분|바퀴|몇 시간|시간 몇 분/.test(p)) 후보.push('긴바늘이 한 바퀴 도는 동안 60분이 지나고, 그동안 짧은바늘은 숫자 한 칸을 움직여요. 60분이 1시간이에요.', '긴바늘이 한 바퀴 도는 동안 작은 눈금이 몇 칸 지나는지 세어 보세요.');
  if (/주일|요일|달력|며칠|개월|몇 월|년/.test(p)) 후보.push('1주일은 7일이에요. 달력에서 같은 요일은 7일마다 바로 아래 칸에 돌아와요.', '1년은 12개월이고, 달마다 날수가 달라요. 달력의 마지막 날짜를 보세요.');
  if (/눈금/.test(p)) 후보.push('긴바늘이 숫자 한 칸을 가면 5분, 작은 눈금 한 칸을 가면 1분이에요. 숫자까지는 5씩, 남은 작은 눈금은 1씩 세어 보세요.');
  if (시계있음 || /바늘|시계/.test(p)) 후보.push("짧은바늘로 '시'를, 긴바늘로 '분'을 읽어요. 짧은바늘이 두 숫자 사이에 있으면 작은 숫자가 '시'이고, 긴바늘은 숫자 한 칸에 5분이에요.");
  if (/[ㄱㄴㄷㄹ] /.test(p)) 후보.push('ㄱ, ㄴ, ㄷ, ㄹ을 하나씩 읽으며 맞으면 ○, 틀리면 ×를 표시해 보세요. 수가 나오면 직접 셈해 확인하세요.');
  return 후보;
};

const 답을말하나 = (글: string, 답: string) => {
  const a = 답.trim();
  return a.length >= 2 && 글.includes(a);
};

// 볼 곳은 아이에게 무엇을 하라는 말(…세요, …니다)로 끝맺습니다.
const 끝말: Array<[RegExp, string]> = [
  [/이에요\.$/, '입니다.'], [/예요\.$/, '입니다.'], [/돼요\.$/, '됩니다.'], [/와요\.$/, '옵니다.'], [/가요\.$/, '갑니다.'], [/나뉘어요\.$/, '나뉩니다.'],
  [/걸려요\.$/, '걸립니다.'], [/있어요\.$/, '있습니다.'], [/져요\.$/, '집니다.'], [/해요\.$/, '합니다.'], [/읽어요\.$/, '읽습니다.'], [/지나요\.$/, '지납니다.'],
  [/움직여요\.$/, '움직입니다.'], [/같아요\.$/, '같습니다.'], [/빼요\.$/, '뺍니다.'], [/세어요\.$/, '셉니다.'], [/되풀이돼요\.$/, '되풀이됩니다.'],
];
const 끝맺기 = (h: string) => {
  const t = h.trim();
  if (/(세요|니다)\.?$/.test(t)) return t;
  for (const [꼴, 바꿈] of 끝말) if (꼴.test(t)) return t.replace(꼴, 바꿈);
  return t;
};

/**
 * 시간 문항의 힌트와 풀이입니다. 풀이를 새로 쓸 수 없으면 steps 없이 힌트만
 * 돌려줍니다. 둘 다 없으면 null입니다.
 */
export const 시간도움 = (prompt: string, answer: string, visual?: QuestionVisual): 시간도움결과 | null => {
  const p = prompt.replace(/\s+/g, ' ');
  const 시계있음 = visual?.kind === 'clock';
  // 힌트 후보 가운데 답을 말하지 않는 첫 것을 고릅니다. 모두 답을 말하면 힌트는 바꾸지 않습니다(빈 글).
  const 고르기 = (후보: string[]) => 후보.map((h) => 끝맺기(r(h))).find((h) => !답을말하나(h, answer)) ?? '';
  const 맺기 = (hint: string, steps?: string[]): 시간도움결과 | null => (hint || steps ? { hint, steps: steps?.map(r) } : null);
  for (const 풀기 of [걸린시간, 끝난시각, 바꾸기, 더한시간, 몇분전, 오전오후, 달력, 약속, (q: string, a: string) => 바늘(q, a, visual)]) {
    const 도움 = 풀기(p, answer);
    if (도움) return 맺기(고르기([도움.hint, ...주제힌트(p, 시계있음)]), 도움.steps);
  }
  return 맺기(고르기(주제힌트(p, 시계있음)));
};
