// ── 곱셈 차시의 올림 꼴 ────────────────────────────────────────────
/** 2 올림 없음, 3 십의 자리에서 백을 넘김, 4 일의 자리에서 올림, 5 두 번 */
const 올림꼴 = (a: number, m: number) => {
  const ones = (a % 10) * m;
  const tens = Math.floor(a / 10) * m + Math.floor(ones / 10);
  const 일올림 = ones >= 10; const 백넘김 = tens >= 10;
  return !일올림 && !백넘김 ? 2 : !일올림 ? 3 : !백넘김 ? 4 : 5;
};
/** 그 차시 꼴에 맞는 (두 자리 수, 한 자리 수)를 고릅니다. */
const 꼴수 = (next: (n: number) => number, 차시: number, 아래 = 11, 위 = 99): [number, number] | null => {
  for (let k = 0; k < 40; k += 1) {
    const a = 사이(next, 아래, 위); const m = 사이(next, 2, 9);
    if (a % 10 === 0 && 차시 !== 3) continue;
    if (올림꼴(a, m) === 차시) return [a, m];
  }
  return null;
};

