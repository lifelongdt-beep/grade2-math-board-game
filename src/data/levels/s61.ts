const 기둥뿔견주기: G5Family = {
  id: 'prism-vs-pyramid',
  make: (seed) => {
    const next = 고르개(seed);
    const 물음 = next(2);
    const n = 물음 === 0 ? 사이(next, 3, 5) : 사이(next, 3, 9);
    // n각기둥의 꼭짓점(2n)과 같은 꼭짓점을 가진 각뿔은 (2n-1)각뿔
    if (물음 === 0) {
      const m = 2 * n - 1;
      if (m > 10) return null;
      return 사고({
        prompt: `${각이름[n]}각기둥과 꼭짓점의 수가 같은 각뿔의 이름은 무엇일까요?`,
        answer: `${각이름[m]}각뿔`,
        wrongs: [n, m - 1, m + 1].filter((k) => k >= 3 && k <= 10 && k !== m).map((k) => `${각이름[k]}각뿔`).concat(`${각이름[n]}각기둥`).slice(0, 4),
        tag: 'solid',
        strategy: '각기둥과 각뿔의 구성 요소 견주기',
        hint: '각기둥과 각뿔의 꼭짓점은 밑면의 변의 수와 어떤 관계가 있나요?',
        steps: [`${각이름[n]}각기둥의 꼭짓점은 ${n}×2=${2 * n}(개)입니다.`, `꼭짓점이 ${2 * n}개인 각뿔은 밑면의 변이 ${2 * n}-1=${m}(개)인 ${각이름[m]}각뿔입니다.`],
      });
    }
    // 같은 밑면일 때 모서리 차는 n
    return 사고({
      prompt: `${각이름[n]}각기둥과 ${각이름[n]}각뿔의 모서리의 수의 차는 몇 개일까요?`,
      answer: `${n}개`,
      wrongs: [`${2 * n}개`, `${n + 1}개`, `${3 * n}개`, `1개`].filter((w) => w !== `${n}개`),
      tag: 'solid',
      strategy: '각기둥과 각뿔의 구성 요소 견주기',
      hint: '두 입체도형의 모서리를 각각 밑면의 변의 수로 나타내 보세요.',
      steps: [`${각이름[n]}각기둥의 모서리는 ${3 * n}개, ${각이름[n]}각뿔의 모서리는 ${2 * n}개입니다.`, `${3 * n}-${2 * n}=${n}(개)입니다.`],
    });
  },
};

// ── 3단원 소수의 나눗셈 ─────────────────────────────────────────────
const 몫거꾸로식: G5Family = {
  id: 'decimal-div-which',
  make: (seed) => {
    const next = 고르개(seed);
    const d = 사이(next, 2, 9);
    const q = 사이(next, 101, 499);
    const n = q * d;
    const 자리 = 1 + next(2);
    const 몫 = q / 10 ** 자리;
    const 답식 = `${(n / 10 ** 자리).toFixed(자리)}÷${d}`;
    const 몫글 = 몫.toFixed(자리);
    return 사고({
      prompt: `${n}÷${d}=${q}을(를) 이용하여 몫이 ${몫글}이(가) 되는 나눗셈식을 찾으면 어느 것일까요?`,
      answer: 답식,
      wrongs: [0, 1, 2, 3].filter((k) => k !== 자리).map((k) => `${(n / 10 ** k).toFixed(k)}÷${d}`).concat(`${n}÷${d * 10}`).filter((w) => w !== 답식).slice(0, 4),
      tag: 'decimal',
      strategy: '나누어지는 수와 몫의 관계로 거꾸로 식 찾기',
      hint: '나누는 수가 같을 때, 나누어지는 수가 1/10배가 되면 몫은 어떻게 될까요?',
      steps: [`몫 ${몫글}은(는) ${q}의 1/${10 ** 자리}배입니다.`, `나누는 수가 같으므로 나누어지는 수도 ${n}의 1/${10 ** 자리}배인 ${(n / 10 ** 자리).toFixed(자리)}입니다.`, `그러므로 ${답식}입니다.`],
      minusIsOperator: true,
    });
  },
};

const 소수나눗셈바로: G5Family = {
  id: 'decimal-div-basic',
  make: (seed) => {
    const next = 고르개(seed);
    const d = 사이(next, 2, 9);
    const q = 사이(next, 11, 49);
    const n = (q * d) / 10;
    return 지식({
      prompt: `${n.toFixed(1)}÷${d}은(는) 얼마일까요?`,
      answer: (q / 10).toFixed(1),
      wrongs: [String(q), (q / 100).toFixed(2), ((q + 1) / 10).toFixed(1), (q * 10).toFixed(0)],
      tag: 'decimal',
      strategy: '(소수)÷(자연수) 계산하기',
      hint: `${Math.round(n * 10)}÷${d}의 몫을 먼저 구해 보세요.`,
      steps: [`${Math.round(n * 10)}÷${d}=${q}이므로 ${n.toFixed(1)}÷${d}=${(q / 10).toFixed(1)}입니다.`],
    });
  },
};

const 대분수가분수: G5Family = {
  id: 'mixed-to-improper',
  make: (seed) => {
    const next = 고르개(seed);
    const w = 사이(next, 1, 5);
    const d = 사이(next, 2, 9);
    const n = 사이(next, 1, d - 1);
    // 문제의 분수는 기약분수로 둡니다(4와 2/4처럼 쓰지 않습니다).
    const 공약 = (x: number, y: number): number => (y ? 공약(y, x % y) : x);
    if (공약(n, d) !== 1) return null;
    return 지식({
      prompt: `(대분수)÷(자연수)를 계산하려고 ${w}과(와) ${n}/${d}을(를) 가분수로 나타내면 무엇일까요?`,
      answer: `${w * d + n}/${d}`,
      wrongs: [`${w + n}/${d}`, `${w * n + d}/${d}`, `${w * d}/${d}`, `${w * d + n}/${d * w}`].filter((x) => x !== `${w * d + n}/${d}`),
      tag: 'fraction',
      strategy: '대분수를 가분수로 나타내기',
      hint: '자연수 부분은 분모가 같은 분수로 몇이 되나요?',
      steps: [`${w}=${w * d}/${d}이므로 ${w * d}/${d}+${n}/${d}=${w * d + n}/${d}입니다.`],
      sameValueOk: true,
    });
  },
};

