/** 구성 요소 하나의 수를 주고 다른 요소의 수를 거꾸로 구합니다. */
const 구성거꾸로 = (뿔: boolean): G5Family => ({
  id: 뿔 ? 'pyramid-parts-back' : 'prism-parts-back',
  make: (seed) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 10);
    const 이름 = `${각이름[n]}${뿔 ? '각뿔' : '각기둥'}`;
    const 면 = 뿔 ? n + 1 : n + 2;
    const 모서리 = 뿔 ? 2 * n : 3 * n;
    const 꼭짓점 = 뿔 ? n + 1 : 2 * n;
    const 종류 = next(3);
    if (종류 === 0) {
      return 사고({
        prompt: `모서리가 ${모서리}개인 ${뿔 ? '각뿔' : '각기둥'}이 있습니다. 이 ${뿔 ? '각뿔' : '각기둥'}의 꼭짓점은 몇 개일까요?`,
        answer: `${꼭짓점}개`,
        wrongs: [`${모서리}개`, `${면}개`, `${꼭짓점 + 2}개`, `${뿔 ? 2 * n : n + 1}개`].filter((w) => w !== `${꼭짓점}개`),
        tag: 'solid',
        strategy: '모서리의 수로 밑면의 모양을 거꾸로 찾아 꼭짓점 세기',
        hint: `${뿔 ? '각뿔의 모서리는 밑면의 변의 수의 몇 배인가요?' : '각기둥의 모서리는 밑면의 변의 수의 몇 배인가요?'}`,
        steps: [`${뿔 ? '각뿔' : '각기둥'}의 모서리는 밑면의 변의 수의 ${뿔 ? 2 : 3}배이므로 밑면의 변은 ${모서리}÷${뿔 ? 2 : 3}=${n}(개)입니다.`, `${이름}의 꼭짓점은 ${꼭짓점}개입니다.`],
      });
    }
    if (종류 === 1) {
      const 합 = 면 + 모서리 + 꼭짓점;
      return 사고({
        prompt: `면, 모서리, 꼭짓점의 수를 모두 더하면 ${합}개인 ${뿔 ? '각뿔' : '각기둥'}의 이름은 무엇일까요?`,
        answer: 이름,
        wrongs: [n - 1, n + 1, n + 2].filter((k) => k >= 3 && k <= 10).map((k) => `${각이름[k]}${뿔 ? '각뿔' : '각기둥'}`).concat(`${각이름[n]}${뿔 ? '각기둥' : '각뿔'}`).slice(0, 4),
        tag: 'solid',
        strategy: '구성 요소의 수 사이의 관계로 입체도형 찾기',
        hint: `밑면의 변의 수를 □라 하면 면, 모서리, 꼭짓점은 각각 □로 어떻게 나타낼 수 있을까요?`,
        steps: [뿔 ? `각뿔의 면은 □+1, 모서리는 □×2, 꼭짓점은 □+1이므로 합은 □×4+2입니다.` : `각기둥의 면은 □+2, 모서리는 □×3, 꼭짓점은 □×2이므로 합은 □×6+2입니다.`, `${합}-2=${합 - 2}, ${합 - 2}÷${뿔 ? 4 : 6}=${n}이므로 밑면은 ${각이름[n]}각형입니다.`, `그러므로 ${이름}입니다.`],
      });
    }
    return 사고({
      prompt: `꼭짓점이 ${꼭짓점}개인 ${뿔 ? '각뿔' : '각기둥'}이 있습니다. 이 ${뿔 ? '각뿔' : '각기둥'}의 모서리는 몇 개일까요?`,
      answer: `${모서리}개`,
      wrongs: [`${꼭짓점}개`, `${면}개`, `${모서리 + n}개`, `${모서리 - 1}개`].filter((w) => w !== `${모서리}개`),
      tag: 'solid',
      strategy: '꼭짓점의 수로 밑면의 모양을 거꾸로 찾아 모서리 세기',
      hint: `${뿔 ? '각뿔의 꼭짓점은 밑면의 꼭짓점에 하나가 더 있습니다.' : '각기둥의 꼭짓점은 두 밑면에 똑같이 나뉘어 있습니다.'}`,
      steps: [`${뿔 ? `밑면의 변은 ${꼭짓점}-1=${n}(개)입니다.` : `밑면의 변은 ${꼭짓점}÷2=${n}(개)입니다.`}`, `${이름}의 모서리는 ${모서리}개입니다.`],
    });
  },
});

