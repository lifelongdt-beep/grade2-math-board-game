const 읽기 = (n: number) => {
  const 자리 = [Math.floor(n / 100), Math.floor(n / 10) % 10, n % 10];
  const 말 = (d: number, 단위: string) => (d === 0 ? '' : `${d === 1 && 단위 ? '' : 일이삼[d]}${단위}`);
  return `${말(자리[0], '백')}${말(자리[1], '십')}${자리[2] ? 일이삼[자리[2]] : ''}`;
};

