const 몫어림견주기: G5Family = {
  id: 'quotient-estimate-compare',
  make: (seed) => {
    const next = 고르개(seed);
    const 식들 = 섞기([0, 1, 2, 3], next).map(() => {
      const 나누는 = 사이(next, 2, 9) / (next(2) ? 1 : 10);
      const 몫 = 사이(next, 2, 60) / (next(2) ? 1 : 10);
      return { 나누는, 몫, 나누어지는: Math.round(나누는 * 몫 * 1000) / 1000 };
    });
    const 몫들 = 식들.map((x) => x.나누어지는 / x.나누는);
    const 큰 = Math.max(...몫들);
    if (몫들.filter((x) => Math.abs(x - 큰) < 1e-9).length > 1) return null;
    if ([...몫들].sort((a, b) => b - a)[1] * 1.5 > 큰) return null;
    const 글 = 식들.map((x) => `${소수(x.나누어지는)}÷${소수(x.나누는)}`);
    const 답 = 글[몫들.indexOf(큰)];
    return 사고({
      prompt: '계산하지 않고 어림하여 몫이 가장 큰 나눗셈식을 찾으면 어느 것일까요?',
      answer: 답,
      wrongs: 글.filter((x) => x !== 답),
      tag: 'decimal',
      strategy: '어림셈으로 몫의 크기 견주기',
      hint: '나누어지는 수와 나누는 수를 가까운 자연수로 어림해 몫을 대강 구해 보세요. 나누는 수가 1보다 작으면 몫은 나누어지는 수보다 커집니다.',
      steps: [글.map((x, k) => `${x}≈${Math.round(몫들[k])}`).join(', '), `몫이 가장 큰 것은 ${답}입니다.`],
      sameValueOk: true,
    });
  },
};

