const 대분수가분수: G5Family = {
  id: 'mixed-to-improper-62',
  make: (seed) => {
    const next = 고르개(seed);
    const w = 사이(next, 1, 5);
    const d = 사이(next, 2, 9);
    const n = 사이(next, 1, d - 1);
    const 공약 = (x: number, y: number): number => (y ? 공약(y, x % y) : x);
    if (공약(n, d) !== 1) return null;
    return 지식({
      prompt: `(대분수)÷(분수)를 계산하려고 ${w}과(와) ${n}/${d}을(를) 가분수로 나타내면 무엇일까요?`,
      answer: `${w * d + n}/${d}`,
      wrongs: [`${w + n}/${d}`, `${w * n + d}/${d}`, `${w * d}/${d}`, `${w * d + n}/${d * w}`].filter((x) => x !== `${w * d + n}/${d}`),
      tag: 'fraction',
      strategy: '대분수를 가분수로 나타내기',
      hint: '자연수 부분은 분모가 같은 분수로 몇이 되나요?',
      steps: [`${w}=${w * d}/${d}이므로 ${w * d}/${d}+${n}/${d}=${w * d + n}/${d}입니다.`],
      sameValueOk: true,
    });
  },
};

