const 시각 = (h: number, m: number) => (m ? `${h}시 ${m}분` : `${h}시`);
const 몇시간몇분 = (분: number) => (분 % 60 ? `${Math.floor(분 / 60)}시간 ${분 % 60}분` : `${분 / 60}시간`);
