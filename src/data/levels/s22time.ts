type 결 = 0 | 1 | 2;
const 결로 = (k: 결) => (k === 0 ? 지식 : k === 1 ? 적용 : 사고);
type 수꼴 = Omit<G5Spec, '결' | 'answer' | 'wrongs' | 'tag'> & { 단위?: string; 후보: number[]; 위?: number };

const 수로 = (k: 결, 답: number, o: 수꼴): G5Spec | null => {
  const { 단위 = '', 후보, 위 = 1440, ...rest } = o;
  if (!Number.isInteger(답) || 답 < 0) return null;
  const wrongs = 수오답(답, 후보, 단위, 0, 위);
  return wrongs.length < 3 ? null : 결로(k)({ ...rest, tag: 'time', ownTimeSteps: true, answer: `${답}${단위}`, wrongs });
};
const 글로 = (k: 결, 답: string, 오답: string[], o: Omit<G5Spec, '결' | 'answer' | 'wrongs' | 'tag'>): G5Spec | null => {
  const wrongs = [...new Set(오답)].filter((w) => w !== 답).slice(0, 3);
  return wrongs.length < 3 ? null : 결로(k)({ ...o, tag: 'time', ownTimeSteps: true, answer: 답, wrongs });
};

const 가족 = (id: string, make: (next: (n: number) => number) => G5Spec | null): G5Family => ({ id: `time22-${id}`, 최대: 3, make: (seed) => make(고르개(seed)) });
