const 대분수바로 = (빼기: boolean): G5Family => ({
  id: `mixed-basic-${빼기 ? 'sub' : 'add'}`,
  make: (seed) => {
    const next = 고르개(seed);
    const d = 사이(next, 4, 9);
    const a = 사이(next, 1, d - 2);
    const b = 사이(next, 1, d - 1 - a);
    const w1 = 사이(next, 2, 5);
    const w2 = 사이(next, 1, w1 - 1);
    const [자, 분] = 빼기 ? [w1 - w2, a + b - b] : [w1 + w2, a + b];
    const 앞 = 빼기 ? `${w1}과(와) ${a + b}/${d}` : `${w1}과(와) ${a}/${d}`;
    const 뒤 = 빼기 ? `${w2}과(와) ${b}/${d}` : `${w2}과(와) ${b}/${d}`;
    const 답 = `${자}과(와) ${분}/${d}`;
    return 지식({
      prompt: `${앞} ${빼기 ? '-' : '+'} ${뒤}은(는) 얼마일까요?`,
      answer: 답,
      wrongs: [`${자}과(와) ${분}/${d * 2}`, `${자 + 1}과(와) ${분}/${d}`, `${자}과(와) ${분 + 1 < d ? 분 + 1 : 분 - 1}/${d}`].filter((w) => w !== 답),
      tag: 'fraction',
      strategy: `분모가 같은 대분수의 ${빼기 ? '뺄셈' : '덧셈'} 하기`,
      hint: '자연수는 자연수끼리, 분수는 분수끼리 계산하세요.',
      steps: [`자연수끼리 ${w1}${빼기 ? '-' : '+'}${w2}=${자}, 분수끼리 ${빼기 ? a + b : a}/${d}${빼기 ? '-' : '+'}${b}/${d}=${분}/${d}입니다.`, `그러므로 ${답}입니다.`],
      minusIsOperator: true,
    });
  },
});

