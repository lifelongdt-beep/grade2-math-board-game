// 2-2 4단원 5차시 '1시간을 알아볼까요'
// ────────────────────────────────────────────────────────────────────
// 이 차시에서 배우는 것은 '긴바늘이 한 바퀴 도는 데 걸리는 시간은 60분이고
// 60분은 1시간이다'입니다. 80분을 1시간 20분으로, 1시간 25분을 85분으로
// 바꾸는 것은 다음 차시(걸린 시간을 알아볼까요)에서 시간 띠로 배웁니다.
// 앞서는 이 차시 문항 대부분이 그 바꾸기여서 아이들이 풀 수 없었습니다
// (선생님 말씀). 그래서 이 차시에는
//   · 60분 안의 분(긴바늘이 숫자 몇 칸, 1시간 채우기, 남은 시간)
//   · 몇 시간 ↔ 몇십 분(60분, 120분, 180분 …)
//   · 긴바늘·짧은바늘이 돈 만큼 지난 시간과 그 뒤의 시각
// 만 냅니다. questionFactory.ts는 이 차시에서 '몇 시간 몇 분'이나 60분을
// 넘는 몇십 분(80분 같은 것)이 나오는 문항을 걸러 냅니다(한시간범위).
// ════════════════════════════════════════════════════════════════════

type 결 = 0 | 1 | 2;
const 결로 = (k: 결) => (k === 0 ? 지식 : k === 1 ? 적용 : 사고);
type 수꼴 = Omit<G5Spec, '결' | 'answer' | 'wrongs' | 'tag'> & { 단위?: string; 후보: number[]; 위?: number; 아래?: number };

const 수로 = (k: 결, 답: number, o: 수꼴): G5Spec | null => {
  const { 단위 = '', 후보, 위 = 600, 아래 = 0, ...rest } = o;
  if (!Number.isInteger(답) || 답 < 아래 || 답 > 위) return null;
  // 보기에도 '80분'처럼 다음 차시의 수가 나오지 않게 합니다.
  const 쓸후보 = 후보.filter((v) => 단위 !== '분' || v <= 60 || v % 60 === 0);
  const wrongs = 수오답(답, 쓸후보, 단위, 아래, 위).filter((w) => 한시간범위(w));
  return wrongs.length < 3 ? null : 결로(k)({ ...rest, tag: 'time', ownTimeSteps: true, answer: `${답}${단위}`, wrongs });
};
const 글로 = (k: 결, 답: string, 오답: string[], o: Omit<G5Spec, '결' | 'answer' | 'wrongs' | 'tag'>): G5Spec | null => {
  const wrongs = [...new Set(오답)].filter((w) => w !== 답 && 한시간범위(w)).slice(0, 3);
  return wrongs.length < 3 ? null : 결로(k)({ ...o, tag: 'time', ownTimeSteps: true, answer: 답, wrongs });
};

/** 이 차시에서 다루지 않는 '몇 시간 몇 분'이나 60분을 넘는 몇십 분이 없는지 */
export const 한시간범위 = (글: string) =>
  !/\d+\s*시간\s*\d+\s*분/.test(글) && ![...글.matchAll(/(\d+)\s*분/g)].some((m) => Number(m[1]) > 60 && Number(m[1]) % 60 !== 0);

const 가족 = (id: string, make: (next: (n: number) => number) => G5Spec | null): G5Family => ({ id: `hour22-${id}`, make: (seed) => make(고르개(seed)) });
const 사람 = ['서연', '도윤', '하은', '지호', '수아', '예준', '시우', '하린'];
const 이름 = (next: (n: number) => number) => 사람[next(사람.length)];
const 시각 = (h: number, m: number) => (m ? `${h}시 ${m}분` : `${h}시`);
const 시계 = (h: number, m: number, label: string): ClockVisual => ({ kind: 'clock', label, hour: h, minute: m });
const 한시간막대 = (n: number): BarModelVisual => ({
  kind: 'bar-model', label: '1시간씩 이어 붙인 시간',
  bars: [{ label: `${n}시간`, value: 60 * n, text: Array.from({ length: n }, () => '1시간').join(' + ') }],
});
const 합식 = (n: number) => Array.from({ length: n }, () => '60').join('+');
const 활동 = ['책 읽기', '줄넘기', '그림 그리기', '피아노 연습', '숙제', '블록 놀이', '종이접기', '산책'];
const 수업 = ['체육 수업', '만들기 활동', '운동회 연습', '미술 수업', '줄넘기 연습', '연극 연습'];

