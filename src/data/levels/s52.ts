const 소수 = (x: number) => String(Math.round(x * 10000) / 10000);
const 자리수 = (x: number) => (String(x).split('.')[1] ?? '').length;

// ── 4단원 소수의 곱셈 ───────────────────────────────────────────────
type 곱꼴 = '작×자' | '큰×자' | '자×작' | '자×큰' | '작×작' | '큰×큰';
const 곱수 = (꼴: 곱꼴, next: (n: number) => number): [number, number] => {
  const 작 = () => 사이(next, 2, 9) / 10 + (next(2) ? 사이(next, 1, 9) / 100 : 0);
  const 큰 = () => 사이(next, 1, 9) + 사이(next, 1, 9) / 10;
  const 자 = () => 사이(next, 2, 9);
  const 표: Record<곱꼴, () => [number, number]> = {
    '작×자': () => [작(), 자()],
    '큰×자': () => [큰(), 자()],
    '자×작': () => [자(), 작()],
    '자×큰': () => [자(), 큰()],
    '작×작': () => [작(), 작()],
    '큰×큰': () => [큰(), 큰()],
  };
  return 표[꼴]();
};

