/** 숫자가 나타내는 값이 가장 큰 수 고르기. 자릿수는 차시 범위에 맞춥니다(다섯 자리, 여덟 자리). */
const 자리값가장큰 = (자릿수: number): G5Family => ({
  id: `digit-value-largest-${자릿수}`,
  make: (seed) => {
    const next = 고르개(seed);
    const d = 사이(next, 2, 9);
    // 숫자 d가 서로 다른 자리에 있는 네 수를 만듭니다(맨 앞자리는 빼서 수의 크기만 보고 고르지 않게).
    const 자리들 = 섞기(Array.from({ length: 자릿수 - 1 }, (_, k) => k), next).slice(0, 4);
    const 수들 = 자리들.map((자리) => {
      const 칸 = Array.from({ length: 자릿수 }, () => 0);
      for (let k = 0; k < 자릿수; k += 1) {
        let v = 사이(next, 0, 9);
        if (v === d) v = (v + 1) % 10;
        칸[k] = v;
      }
      칸[0] = 칸[0] === 0 ? (d === 1 ? 2 : 1) : 칸[0];
      칸[자릿수 - 1 - 자리] = d;
      return 칸.join('');
    });
    if (수들.some((n) => n.split('').filter((c) => c === String(d)).length !== 1)) return null;
    const 큰자리 = Math.max(...자리들);
    const 답 = 수들[자리들.indexOf(큰자리)];
    const 이름 = ['일', '십', '백', '천', '만', '십만', '백만', '천만'];
    return 사고({
      prompt: `숫자 ${d}이(가) 나타내는 값이 가장 큰 수는 어느 것일까요?`,
      answer: 답,
      wrongs: 수들.filter((one) => one !== 답),
      tag: 'number',
      strategy: '숫자가 놓인 자리로 값 견주기',
      hint: '수의 크기가 아니라 숫자가 어느 자리에 있는지를 보세요.',
      steps: [...수들.map((n, k) => `${n}에서 ${d}은(는) ${이름[자리들[k]]}의 자리 숫자입니다.`), `가장 높은 자리에 있는 것은 ${답}입니다.`],
      sameValueOk: true,
    });
  },
});

