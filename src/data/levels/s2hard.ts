/** 두 부등식에 공통으로 들어갈 숫자 */
const 공통숫자 = 가족('common-digit', (next) => {
  const t = 사이(next, 2, 8);
  const h = 사이(next, 1, 9); const u1 = 사이(next, 1, 9); const u2 = 사이(next, 0, u1 - 1);
  const m = 사이(next, 1, 8); const n = 사이(next, 0, 9);
  const m2 = 사이(next, m, 9); const n2 = m2 === m ? 사이(next, Math.min(9, n + 1), 9) : 사이(next, 0, 9);
  if (m2 * 10 + n2 <= m * 10 + n) return null;
  return 수로(t, {
    prompt: `1부터 9까지의 숫자 중 □ 안에 공통으로 들어갈 수 있는 숫자는 무엇일까요? ${h}${t}${u1} > ${h}□${u2}, ${t}${m}${n} < □${m2}${n2}`,
    후보: [t - 1, t + 1, t + 2 <= 9 ? t + 2 : t - 2, u1], 위: 9, 아래: 1,
    tag: 'placeValue', strategy: '두 조건을 함께 만족하는 숫자 찾기',
    hint: '부등식마다 □에 들어갈 수 있는 숫자를 따로 구한 다음, 두 쪽에 모두 들어가는 숫자를 찾아보세요.',
    concept: '세 자리 수의 크기 비교: 백의 자리부터 비교하고, 같으면 십의 자리, 그다음 일의 자리를 비교합니다.',
    steps: [`1단계: ${h}${t}${u1} > ${h}□${u2}에서 일의 자리가 ${u1} > ${u2}이므로 □는 ${t}이거나 ${t}보다 작아야 합니다.`, `2단계: ${t}${m}${n} < □${m2}${n2}에서 ${m2}${n2}이(가) ${m}${n}보다 크므로 □는 ${t}이거나 ${t}보다 커야 합니다.`, `3단계: 두 조건을 모두 만족하는 숫자는 ${t}입니다.`],
    misconceptionTip: '□가 같은 숫자일 때도 되는지 꼭 따져 보세요. 낮은 자리의 수가 크기를 정해요.',
  });
});

