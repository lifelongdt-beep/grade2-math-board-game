/** 모눈 위 꺾은 선의 길이 */
const 모눈선 = (칸길이들: number[]) => 가족(`grid-path-${칸길이들[0]}`, (next) => {
  const cols = 6; const rows = 4; const 칸 = 칸길이들[next(칸길이들.length)];
  let c = 0; let r = 사이(next, 0, rows);
  const path: Array<[number, number]> = [[c, r]];
  while (c < cols) {
    const 가로 = Math.min(cols - c, 사이(next, 1, 2));
    for (let k = 0; k < 가로; k += 1) { c += 1; path.push([c, r]); }
    if (c >= cols) break;
    const 새줄 = 사이(next, 0, rows);
    while (r !== 새줄) { r += r < 새줄 ? 1 : -1; path.push([c, r]); }
  }
  const 마디 = path.length - 1; const 세로 = 마디 - cols;
  if (세로 < 2) return null;
  const 답 = 마디 * 칸;
  return 수로(답, {
    prompt: `한 칸의 길이가 ${칸} cm인 모눈 위에 빨간 선을 그었습니다. 그린 빨간 선의 길이는 몇 cm일까요?`,
    단위: ' cm', 후보: [cols * 칸, 마디, (마디 - 1) * 칸, (마디 + 1) * 칸], 위: 1000,
    tag: 'measurement', strategy: '선이 지나간 칸의 수 세기',
    hint: `빨간 선이 모눈 한 칸의 변을 몇 번 지나가는지 세어 보세요. 한 칸은 ${칸} cm입니다.`,
    concept: `길이 재기: 같은 길이가 몇 번인지 알면 길이를 구할 수 있습니다. ${칸} cm가 □번이면 ${칸}을 □번 더한 길이입니다.`,
    steps: [`1단계: 가로로 지나간 칸은 ${cols}칸, 세로로 지나간 칸은 ${세로}칸입니다.`, `2단계: 모두 ${cols}+${세로}=${마디}(칸)입니다.`, `3단계: ${칸} cm가 ${마디}번이므로 ${Array(마디).fill(칸).join('+')}=${답}(cm)입니다.`],
    misconceptionTip: '가로로 지나간 칸만 세면 세로로 꺾인 부분이 빠집니다. 꺾인 곳마다 점을 짚어 가며 세어 보세요.',
    visual: { kind: 'grid-path', label: `한 칸이 ${칸} cm인 모눈 위의 빨간 꺾은 선`, cols, rows, cell: `${칸} cm`, path },
  });
});
const 모눈선cm = 모눈선([1, 2, 3]);
