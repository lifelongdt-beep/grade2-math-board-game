/** 앞쪽과 오른쪽으로 갈수록 낮아지게 쌓은 모양(꼭대기가 모두 보입니다) */
const 쌓은모양 = (next: (n: number) => number, 최소: number, 최대: number): number[][] | null => {
  const 줄 = 사이(next, 1, 2); const 열 = 사이(next, 2, 3);
  const h = Array.from({ length: 줄 }, () => Array(열).fill(0) as number[]);
  for (let r = 0; r < 줄; r += 1) for (let c = 0; c < 열; c += 1) {
    const 위한계 = Math.min(r > 0 ? h[r - 1][c] : 3, c > 0 ? h[r][c - 1] : 3);
    h[r][c] = 위한계 === 0 ? 0 : 사이(next, r === 0 && c === 0 ? 2 : 0, 위한계);
  }
  const 모두 = h.flat().reduce((a, b) => a + b, 0);
  if (h.some((row) => row.every((v) => v === 0)) || h.every((row) => row.at(-1) === 0)) return null;
  return 모두 < 최소 || 모두 > 최대 ? null : h;
};
const 합 = (h: number[][]) => h.flat().reduce((a, b) => a + b, 0);
const 층수 = (h: number[][], k: number) => h.flat().filter((v) => v >= k).length;

/** 그림과 똑같이 쌓고 남는 쌓기나무 */
