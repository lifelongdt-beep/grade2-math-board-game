/** 두 사람의 수 카드 모으기 비교 */
const 모으기비교 = 가족('gather-compare', (next) => {
  const [p, q] = 두이름(next);
  const a = 사이(next, 1, 6); const b = 사이(next, 1, 9 - a); const c = 사이(next, 1, 6); const d = 사이(next, 1, 9 - c);
  if (a + b === c + d) return null;
  const 큰 = a + b > c + d ? p : q;
  return 사고({
    prompt: `${p}은(는) 수 카드 ${a}과(와) ${b}을(를), ${q}은(는) 수 카드 ${c}과(와) ${d}을(를) 모으기 했습니다. 모으기 한 수가 더 큰 사람은 누구일까요?`,
    answer: 큰, wrongs: [큰 === p ? q : p, '두 사람이 같습니다', '알 수 없습니다'],
    tag: 'addition', strategy: '모으기 한 수 비교하기',
    hint: '두 사람이 모으기 한 수를 각각 먼저 구한 다음, 어느 쪽이 더 큰지 비교해 보세요.',
    concept: '수 모으기: 두 수를 합하여 하나의 수로 만드는 것입니다. 덧셈의 기초가 됩니다.',
    steps: [`1단계: ${p}: ${a}과(와) ${b}을(를) 모으면 ${a + b}입니다.`, `2단계: ${q}: ${c}과(와) ${d}을(를) 모으면 ${c + d}입니다.`, `3단계: ${Math.max(a + b, c + d)}이(가) ${Math.min(a + b, c + d)}보다 크므로 ${큰}입니다.`],
    misconceptionTip: '카드 한 장의 수가 크다고 모으기 한 수도 큰 것은 아닙니다. 두 장을 모은 수끼리 비교해요.',
  });
});

/** 두 수를 가르기 해서 넷 중 셋이 같을 때 다른 수 */
