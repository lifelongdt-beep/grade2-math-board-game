type 꼴 = Omit<G5Spec, '결' | 'answer' | 'wrongs'> & { 단위?: string; 후보: number[]; 위?: number; 아래?: number };

/** 수 하나가 답인 고난도 문항입니다. 보기 셋은 그 유형에서 하는 실수로 고릅니다. */
const 수로 = (답: number, o: 꼴): G5Spec | null => {
  const { 단위 = '', 후보, 위, 아래 = 0, ...rest } = o;
  if (!Number.isInteger(답) || 답 < 0) return null;
  const wrongs = 수오답(답, 후보, 단위, 아래, 위);
  return wrongs.length < 3 ? null : 사고({ ...rest, answer: `${답}${단위}`, wrongs });
};

const 가족 = (id: string, make: (next: (n: number) => number) => G5Spec | null): G5Family => ({ id: `hard1-${id}`, make: (seed) => make(고르개(seed)) });
const 이름 = (next: (n: number) => number) => 사람[next(사람.length)];
const 두이름 = (next: (n: number) => number): [string, string] => { const [a, b] = 섞기(사람, next); return [a, b]; };
const 째 = ['', '첫째', '둘째', '셋째', '넷째', '다섯째', '여섯째', '일곱째', '여덟째', '아홉째'];

