/** 소수를 군더더기 없이 씁니다(0.30 → 0.3, 2.0 → 2). */
const 소 = (x: number) => String(Number(x.toFixed(6)));
/** 부동소수점 오차 없이 곱합니다. */
const 곱 = (...xs: number[]) => Number(xs.reduce((a, b) => a * b, 1).toFixed(6));
const 합 = (...xs: number[]) => Number(xs.reduce((a, b) => a + b, 0).toFixed(6));
const 자리수 = (x: number) => (소(x).split('.')[1] ?? '').length;

/** 답과 다르고 서로 다른 소수 보기 셋입니다. 모자라면 10배·1/10배·0.1 차이로 채웁니다. */
const 소오답 = (답: number, 후보: number[], 단위 = ''): string[] => {
  const 고른: string[] = [];
  for (const v of [...후보, 답 * 10, 답 / 10, 답 + 0.1, 답 + 1, 답 * 100]) {
    const w = 소(v);
    if (v <= 0 || w === 소(답) || 고른.includes(w)) continue;
    고른.push(w);
  }
  return 고른.slice(0, 3).map((w) => `${w}${단위}`);
};

type 꼴 = Omit<G5Spec, '결' | 'answer' | 'wrongs' | 'tag'> & { 단위?: string; 후보: number[] };
const 소로 = (답: number, o: 꼴): G5Spec | null => {
  const { 단위 = '', 후보, ...rest } = o;
  if (!(답 > 0)) return null;
  const wrongs = 소오답(답, 후보, 단위);
  const answer = `${소(답)}${단위}`;
  // 풀이의 마지막 줄은 답을 보기에 쓴 그대로 말합니다('19.65(cm)' → '19.65 cm').
  const steps = rest.steps.map((s, k) => (k === rest.steps.length - 1 && 단위 ? s.replace(`${소(답)}(${단위.trim()})`, answer) : s));
  return wrongs.length < 3 ? null : 사고({ ...rest, steps, tag: 'decimal', answer, wrongs });
};

const 가족 = (id: string, make: (next: (n: number) => number) => G5Spec | null): G5Family => ({ id: `hard52-${id}`, 최대: 3, make: (seed) => make(고르개(seed)) });
