const 고유 = ['', '하나', '둘', '셋', '넷', '다섯', '여섯', '일곱', '여덟', '아홉'];
const 고유관형 = ['', '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉'];
const 한자 = ['영', '일', '이', '삼', '사', '오', '육', '칠', '팔', '구'];
const 고유십 = ['', '열', '스물', '서른', '마흔', '쉰', '예순', '일흔', '여든', '아흔'];
const 고유관형십 = (n: number) => { const t = Math.floor(n / 10); const o = n % 10; return `${t === 2 && o === 0 ? '스무' : 고유십[t]}${o ? 고유관형[o] : ''}`; };
const 한자어로 = (n: number) => { const t = Math.floor(n / 10); const o = n % 10; return `${t ? `${t === 1 ? '' : 한자[t]}십` : ''}${o ? 한자[o] : ''}`; };

/** 상황에 맞게 수를 읽은 것 고르기. 개수는 우리말(일곱 개), 날짜·번호는 한자어(칠 월). */
const 상황읽기 = (두자리: boolean): G5Family => ({
  id: `read-in-context-${두자리 ? 2 : 1}`,
  make: (seed) => {
    const next = 고르개(seed);
    const n = 두자리 ? 사이(next, 21, 99) : 사이(next, 2, 9);
    if (두자리 && n % 10 === 0) return null;
    const 우리 = 두자리 ? 고유관형십(n) : 고유관형[n];
    const 한 = 두자리 ? 한자어로(n) : 한자[n];
    const 상황 = 두자리
      ? [
          { 글: `색종이 ${n}장`, 바른: `${우리} 장`, 틀린: `${한} 장` },
          { 글: `${n}번 버스`, 바른: `${한} 번 버스`, 틀린: `${우리} 번 버스` },
        ]
      : [
          { 글: `사과 ${n}개`, 바른: `사과 ${우리} 개`, 틀린: `사과 ${한} 개` },
          { 글: `${n}월`, 바른: `${한} 월`, 틀린: `${우리} 월` },
          { 글: `${n}층`, 바른: `${한} 층`, 틀린: `${우리} 층` },
        ];
    const 고른 = 상황[next(상황.length)];
    const 다른 = 상황.filter((x) => x !== 고른);
    return 사고({
      prompt: `'${고른.글}'을(를) 바르게 읽은 것은 어느 것일까요?`,
      answer: 고른.바른,
      wrongs: [고른.틀린, ...다른.map((x) => x.틀린)].filter((w, k, all) => w !== 고른.바른 && all.indexOf(w) === k).slice(0, 3).concat(두자리 ? [`${우리}${한}`] : [`${고유[n]} 개`]).slice(0, 3),
      tag: 'number',
      strategy: '수를 상황에 맞게 읽기',
      hint: '물건의 개수를 셀 때와, 날짜나 번호를 말할 때 읽는 방법이 다릅니다.',
      steps: [`${고른.글}은(는) ${/개|장/.test(고른.글) ? '개수를 세는 것이므로 하나, 둘로' : '번호나 날짜이므로 일, 이로'} 읽습니다.`, `그러므로 ${고른.바른}입니다.`],
    });
  },
});

