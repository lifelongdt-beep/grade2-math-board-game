const 두걸음이야기 = (두자리: boolean): G5Family => ({
  id: `two-step-story-${두자리 ? 2 : 1}`,
  make: (seed) => {
    const next = 고르개(seed);
    // 1학년 1학기는 한 자리 수 범위(9 이하)이므로 보기까지 9를 넘지 않게 합니다.
    const 사과 = 두자리 ? 사이(next, 21, 45) : 사이(next, 3, 4);
    const 적게 = 두자리 ? 사이(next, 1, 9) * (next(2) ? 1 : 10) : 사이(next, 1, 2);
    const 배 = 사과 - 적게;
    if (배 <= 0) return null;
    // 두 자리 수 덧셈은 받아올림이 없게 둡니다(1-2 6단원 범위).
    if (두자리 && ((사과 % 10) + (배 % 10) >= 10 || 사과 + 배 >= 100)) return null;
    const 모두 = 사과 + 배;
    return 사고({
      prompt: `바구니에 사과가 ${사과}개 있고, 배는 사과보다 ${적게}개 적게 있습니다. 바구니에 있는 사과와 배는 모두 몇 개일까요?`,
      answer: `${모두}개`,
      wrongs: [`${사과 + 적게}개`, `${배}개`, `${사과 * 2}개`, `${모두 + 1}개`].filter((w, k, all) => w !== `${모두}개` && all.indexOf(w) === k),
      tag: 'addition',
      strategy: '먼저 모르는 수를 구하고 다시 더하는 두 걸음 이야기 문제',
      hint: '먼저 배가 몇 개인지 구해 보세요.',
      steps: [`배는 ${사과}-${적게}=${배}(개)입니다.`, `사과와 배는 모두 ${사과}+${배}=${모두}(개)입니다.`],
      minusIsOperator: true,
    });
  },
});

