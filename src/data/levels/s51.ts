/** 식의 값을 계산 순서대로 구합니다(괄호, ×÷, +- 차례). */
const 계산 = (식: string): number => {
  const 토큰 = 식.match(/\d+|[+\-×÷()]/g)!;
  let at = 0;
  const 인수 = (): number => {
    const t = 토큰[at++];
    if (t === '(') { const v = 합(); at += 1; return v; }
    return Number(t);
  };
  const 곱 = (): number => {
    let v = 인수();
    while (토큰[at] === '×' || 토큰[at] === '÷') { const op = 토큰[at++]; const r = 인수(); v = op === '×' ? v * r : v / r; }
    return v;
  };
  const 합 = (): number => {
    let v = 곱();
    while (토큰[at] === '+' || 토큰[at] === '-') { const op = 토큰[at++]; const r = 곱(); v = op === '+' ? v + r : v - r; }
    return v;
  };
  return 합();
};

