// ════════════════════════════════════════════════════════════════════
// 풀이가 한 줄뿐인 문항의 풀이 펼치기
// ────────────────────────────────────────────────────────────────────
// 힌트의 '풀이 한 걸음씩'과 틀린 뒤의 '왜?'는 문항의 풀이 걸음(steps)을
// 보여 줍니다. 걸음이 한 줄이면 아이는 답만 보고 까닭은 보지 못합니다.
// 문항의 모양에서 걸음을 다시 펼칠 수 있는 것은 여기서 펼칩니다.
//   · 풀이 과정 문항(① ② ③ … □): 문제에 적힌 과정을 □를 채워 차례로 보입니다.
// ════════════════════════════════════════════════════════════════════

const 원번호 = /[①②③④⑤⑥]/;

/** □를 답으로 채웁니다. □ 뒤에 답과 같은 단위가 붙어 있으면 단위는 한 번만 씁니다(□분 → 20분). */
const 채우기 = (글: string, 답: string) => {
  const 단위 = (/^[\d.,/]+\s?(\D*)$/.exec(답)?.[1] ?? '').trim();
  const 자리 = 글.indexOf('□');
  const 뒤 = 글.slice(자리 + 1);
  if (단위 && 뒤.trimStart().startsWith(단위)) return `${글.slice(0, 자리)}${답}${뒤.trimStart().slice(단위.length)}`;
  return `${글.slice(0, 자리)}${답}${뒤}`;
};

const 끝점 = (글: string) => (/[.?!]$/.test(글.trim()) ? 글.trim() : `${글.trim()}.`);

/**
 * '… 과정입니다. □에 알맞은 수는? ① … ② … ③ …□…' 꼴에서 과정을 걸음으로
 * 펼칩니다. □를 답으로 채우고, 마지막에 원래 풀이를 붙입니다.
 */
export const 과정걸음 = (prompt: string, answer: string, solution: string): string[] | null => {
  if (!원번호.test(prompt) || !prompt.includes('□')) return null;
  const 조각 = prompt.split(원번호).slice(1).map((s) => s.trim()).filter(Boolean);
  if (조각.length < 2) return null;
  // 답이 '20분'처럼 단위를 가지면 □ 자리에 단위째 넣고, □ 뒤의 같은 단위는 지웁니다.
  const 답 = answer.trim();
  const 걸음 = 조각.map((s) => 끝점(s.includes('□') ? 채우기(s, 답) : s));
  const 끝 = solution.trim();
  if (끝 && !걸음.some((s) => s === 끝)) 걸음.push(끝점(끝));
  return 걸음.map((s) => resolveParticles(s));
};

