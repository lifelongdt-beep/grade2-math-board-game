// ════════════════════════════════════════════════════════════════════
// 3-2 5단원 들이와 무게 — 문항 뭉치
// ────────────────────────────────────────────────────────────────────
//   1 단원 도입
//   2 들이 비교   3 들이의 단위(L, mL)   4 들이 어림하고 재기   5 들이의 덧셈과 뺄셈
//   6 무게 비교   7 무게의 단위(kg, g, t)  8 무게 어림하고 재기   9 무게의 덧셈과 뺄셈
//
// 지도서가 못박은 것:
//   · 1 L=1000 mL, 1 kg=1000 g, 1 t=1000 kg. "지나친 단위 환산은 다루지
//     않는다." 그래서 L↔mL, kg↔g, t↔kg만 바꿉니다(t↔g은 하지 않음).
//   · 덧셈·뺄셈은 L는 L끼리, mL는 mL끼리 계산합니다. "받아올림이나
//     받아내림이 있는 계산에 집중하는 것은 지양", 교과서 문제도 받아올림·
//     받아내림이 없습니다(3 L 500 mL+1 L 300 mL, 8 kg 700 g-6 kg 200 g).
//   · 오개념: 높이가 높은 그릇에 더 많이 들어간다고 여김, 큰 물건이 더
//     무겁다고 여김. 임의 단위(컵, 바둑돌)는 크기가 같아야 비교할 수 있음.
//   · 어림은 '약'으로 나타내고, 어림한 값과 잰 값의 차이가 작을수록 잘
//     어림한 것입니다.
// 글은 조사를 '을(를)'처럼 적고, 문항을 만들 때 앞말에 맞춥니다.
// ════════════════════════════════════════════════════════════════════

type 종류 = '들이' | '무게';
const 큰단위: Record<종류, string> = { 들이: 'L', 무게: 'kg' };
const 작은단위: Record<종류, string> = { 들이: 'mL', 무게: 'g' };
/** 작은 단위로 잰 양을 '몇 L 몇 mL'처럼 씁니다. */
const 양글 = (kind: 종류, small: number) => {
  const 큰 = Math.floor(small / 1000);
  const 작은 = small % 1000;
  if (큰 === 0) return `${작은} ${작은단위[kind]}`;
  if (작은 === 0) return `${큰} ${큰단위[kind]}`;
  return `${큰} ${큰단위[kind]} ${작은} ${작은단위[kind]}`;
};

