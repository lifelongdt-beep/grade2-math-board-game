// ── 5, 9차시: 덧셈과 뺄셈(받아올림·받아내림 없음) ────────────────────
const 덧뺄문항 = (kind: 종류, 더하기: boolean, 문장: boolean): G5Family => ({
  id: `${더하기 ? 'add' : 'sub'}-${kind}-${문장 ? 'word' : 'calc'}`,
  make: (seed) => {
    const next = rand(seed + (더하기 ? 9 : 10) + (문장 ? 100 : 0));
    const B = 큰단위[kind];
    const S = 작은단위[kind];
    let a1 = 1 + next(8);
    let a2 = (1 + next(8)) * 100;
    let b1 = 1 + next(8);
    let b2 = (1 + next(8)) * 100;
    if (더하기) {
      if (a2 + b2 >= 1000) return null;
    } else {
      if (a1 < b1) [a1, b1] = [b1, a1];
      if (a2 < b2) [a2, b2] = [b2, a2];
      if (a1 === b1 && a2 === b2) return null;
    }
    const 큰답 = 더하기 ? a1 + b1 : a1 - b1;
    const 작은답 = 더하기 ? a2 + b2 : a2 - b2;
    const 글 = (x: number, y: number) => (y === 0 ? `${x} ${B}` : x === 0 ? `${y} ${S}` : `${x} ${B} ${y} ${S}`);
    const 답 = 글(큰답, 작은답);
    const 식 = `${a1} ${B} ${a2} ${S}${더하기 ? '+' : '-'}${b1} ${B} ${b2} ${S}`;
    const 장면 = kind === '들이'
      ? 더하기
        ? `물통에 물이 ${a1} ${B} ${a2} ${S} 들어 있습니다. 여기에 물 ${b1} ${B} ${b2} ${S}을(를) 더 부었습니다. 물통에 들어 있는 물은 모두 몇 ${B} 몇 ${S}일까요?`
        : `주스가 ${a1} ${B} ${a2} ${S} 있었는데 ${b1} ${B} ${b2} ${S}을(를) 마셨습니다. 남은 주스는 몇 ${B} 몇 ${S}일까요?`
      : 더하기
        ? `고구마 ${a1} ${B} ${a2} ${S}과(와) 감자 ${b1} ${B} ${b2} ${S}을(를) 샀습니다. 산 고구마와 감자의 무게는 모두 몇 ${B} 몇 ${S}일까요?`
        : `밀가루 ${a1} ${B} ${a2} ${S} 가운데 ${b1} ${B} ${b2} ${S}을(를) 빵을 만드는 데 썼습니다. 남은 밀가루는 몇 ${B} 몇 ${S}일까요?`;
    return {
      prompt: 문장 ? 장면 : `${식}을(를) 계산하면 얼마일까요?`,
      answer: 답,
      minusIsOperator: true,
      wrongs: [
        글(큰답, 더하기 ? Math.abs(a2 - b2) : a2 + b2 < 1000 ? a2 + b2 : a2),
        글(큰답 + 1, 작은답),
        글(큰답, 작은답 / 10 || 1),
        글(더하기 ? Math.abs(a1 - b1) || 큰답 + 2 : a1 + b1, 작은답),
      ].filter((w) => w !== 답),
      tag: 'measurement',
      concept: `${kind}의 ${더하기 ? '덧셈' : '뺄셈'}은 ${B}은(는) ${B}끼리, ${S}은(는) ${S}끼리 계산합니다.`,
      strategy: `${kind}의 ${더하기 ? '덧셈' : '뺄셈'}`,
      hint: `${B}끼리, ${S}끼리 따로 ${더하기 ? '더하세요' : '빼세요'}.`,
      steps: [
        ...(문장 ? [`식으로 나타내면 ${식}입니다.`] : []),
        `${B}끼리: ${a1}${더하기 ? '+' : '-'}${b1}=${큰답}`,
        `${S}끼리: ${a2}${더하기 ? '+' : '-'}${b2}=${작은답}`,
        `그러므로 ${답}입니다.`,
      ],
      misconceptionTip: `${B}과(와) ${S}을(를) 섞어서 계산하면 안 됩니다. 같은 단위끼리 계산합니다.`,
    };
  },
});

