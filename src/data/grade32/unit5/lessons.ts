// ── 3, 7차시: 단위 ──────────────────────────────────────────────────
const 바꾸기문항 = (kind: 종류): G5Family => ({
  id: `convert-${kind}`,
  make: (seed) => {
    const next = rand(seed + 5);
    const 큰 = 1 + next(9);
    const 작은 = pick([50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 250, 30, 750], seed + 1);
    const small = 큰 * 1000 + 작은;
    const B = 큰단위[kind];
    const S = 작은단위[kind];
    const 작은쪽으로 = next(2) === 0;
    if (작은쪽으로) {
      return {
        prompt: `${큰} ${B} ${작은} ${S}은(는) 몇 ${S}일까요?`,
        answer: `${small} ${S}`,
        wrongs: [큰 * 100 + 작은, 작은 < 100 ? Number(`${큰}${작은}`) : 큰 * 1000 + 작은 * 10, (큰 + 1) * 1000 + 작은, 큰 * 10000 + 작은].filter((v) => v !== small).map((v) => `${v} ${S}`),
        tag: 'measurement',
        concept: `1 ${B}=1000 ${S}입니다.`,
        strategy: `몇 ${B} 몇 ${S}을(를) 몇 ${S}(으)로 나타내기`,
        hint: `${큰} ${B}은(는) 몇 ${S}인지 먼저 바꾸어 보세요.`,
        steps: [큰 === 1 ? `1 ${B}=1000 ${S}입니다.` : `1 ${B}=1000 ${S}이므로 ${큰} ${B}=${큰 * 1000} ${S}입니다.`, `${큰 * 1000}+${작은}=${small}이므로 ${small} ${S}입니다.`],
        misconceptionTip: `1 ${B}은(는) 100 ${S}이(가) 아니라 1000 ${S}입니다. ${작은 < 100 ? `${큰} ${B} ${작은} ${S}을(를) ${큰}${작은} ${S}(으)로 쓰면 안 됩니다.` : ''}`.trim(),
      };
    }
    return {
      prompt: `${small} ${S}은(는) 몇 ${B} 몇 ${S}일까요?`,
      answer: 양글(kind, small),
      wrongs: [
        `${Math.floor(small / 100)} ${B} ${small % 100} ${S}`,
        `${큰 + 1} ${B} ${작은} ${S}`,
        작은 % 10 === 0 && 작은 >= 100 ? `${큰} ${B} ${작은 / 10} ${S}` : `${큰} ${B} ${작은 * 10} ${S}`,
        `${큰 * 10} ${B} ${작은} ${S}`,
      ].map((w) => w.replace(/ 0 (mL|g)$/, '')),
      tag: 'measurement',
      concept: `1000 ${S}=1 ${B}입니다.`,
      strategy: `몇 ${S}을(를) 몇 ${B} 몇 ${S}(으)로 나타내기`,
      hint: `${small} ${S} 안에 1000 ${S}이(가) 몇 번 들어 있는지 생각해 보세요.`,
      steps: [`${small} ${S}=${큰 * 1000} ${S}+${작은} ${S}입니다.`, `${큰 * 1000} ${S}=${큰} ${B}이므로 ${양글(kind, small)}입니다.`],
      misconceptionTip: `100 ${S}이(가) 1 ${B}인 것이 아닙니다. 1000 ${S}이(가) 1 ${B}입니다.`,
    };
  },
});

