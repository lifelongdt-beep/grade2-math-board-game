// 3-2 3단원 원 — 문항 뭉치
// ────────────────────────────────────────────────────────────────────
//   1 단원 도입
//   2 원의 중심, 반지름, 지름은 무엇일까요(지도서 2~3차시를 한 차시로)
//   3 원에는 어떤 성질이 있을까요
//   4 컴퍼스를 이용하여 원을 어떻게 그릴까요
//
// 지도서가 못박은 것:
//   · 원의 중심 → 반지름 → 지름 차례로 약속합니다. '원의 중심과 원 위의
//     한 점을 이은 선분'이 반지름, '원 위의 두 점을 이은 선분이 원의
//     중심을 지날 때' 그 선분이 지름입니다.
//   · 오개념: 원의 중심을 지나지 않는 선분(현)을 지름으로 여김, 한 원에
//     반지름·지름이 하나뿐이라고 여김. 그래서 지름 고르기에 '중심을
//     지나지 않는 선분'을 꼭 넣고, '무수히 많이 그을 수 있다'를 묻습니다.
//   · 교과서가 명시적으로 다루는 성질: 지름은 원을 똑같이 둘로 나눈다,
//     원 위의 두 점을 이은 선분 중 지름이 가장 길다, 지름은 반지름의
//     2배이다.
//   · 컴퍼스로 원 그리기: ① 원의 중심 정하기 ② 컴퍼스를 반지름만큼
//     벌리기 ③ 침을 원의 중심에 꽂고 돌리기.
//   · 같은 크기의 원 여러 개를 맞닿게·겹치게 놓은 문제(곰곰! 생각해요,
//     단원 평가)는 그림의 좌표를 실제 길이대로 잡아 그립니다.
// 글은 조사를 '을(를)'처럼 적고, 문항을 만들 때 앞말에 맞춥니다.
// ════════════════════════════════════════════════════════════════════

const 글자 = ['ㄱ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ'];
const 위 = (deg: number, r = 1): [number, number] => {
  const t = (deg * Math.PI) / 180;
  return [Math.cos(t) * r, -Math.sin(t) * r];
};
const shuffleWith = <T,>(items: T[], next: (n: number) => number): T[] => {
  const out = [...items];
  for (let k = out.length - 1; k > 0; k -= 1) {
    const j = next(k + 1);
    [out[k], out[j]] = [out[j], out[k]];
  }
  return out;
};

// 선분을 겹치지 않게 놓은 몇 가지 배치입니다(각도, 도). 지름 두 끝, 반지름 끝,
// 중심을 지나지 않는 선분의 두 끝, 원 안의 점(중심에서 0.5)입니다.
const 배치들 = [
  { 지름: [160, 340], 반지름: 75, 현: [215, 290], 안: 30 },
  { 지름: [20, 200], 반지름: 115, 현: [245, 325], 안: 160 },
  { 지름: [100, 280], 반지름: 15, 현: [140, 215], 안: 330 },
  { 지름: [60, 240], 반지름: 150, 현: [275, 355], 안: 115 },
];

// ── 2차시: 원의 중심, 반지름, 지름 ───────────────────────────────────
const 선분찾기문항: G5Family = {
  id: 'find-segment',
  make: (seed) => {
    const next = rand(seed + 1);
    const b = 배치들[next(배치들.length)];
    const 이름 = shuffleWith(글자.slice(0, 5), next);
    const [지1, 지2, 반, 현1, 현2] = 이름;
    const 안이름 = 글자[5];
    const p = {
      [지1]: 위(b.지름[0]), [지2]: 위(b.지름[1]), [반]: 위(b.반지름), [현1]: 위(b.현[0]), [현2]: 위(b.현[1]), [안이름]: 위(b.안, 0.5),
    } as Record<string, [number, number]>;
    const 묻기 = next(2) === 0 ? '지름' : '반지름';
    const 선분 = (a: string, c: string) => `선분 ${[a, c].sort().join('')}`;
    const 지름선 = 선분(지1, 지2);
    const 반지름선 = `선분 ㅇ${반}`;
    const 현선 = 선분(현1, 현2);
    const 안선 = `선분 ㅇ${안이름}`;
    const visual: CircleVisual = {
      kind: 'circles',
      label: '원의 중심 ㅇ과 여러 선분을 그은 원',
      circles: [{ cx: 0, cy: 0, r: 1 }],
      points: [{ x: 0, y: 0, name: 'ㅇ' }, ...Object.entries(p).map(([name, [x, y]]) => ({ x, y, name }))],
      segments: [
        { from: p[지1], to: p[지2] },
        { from: [0, 0], to: p[반] },
        { from: p[현1], to: p[현2] },
        { from: [0, 0], to: p[안이름] },
      ],
    };
    return 묻기 === '지름'
      ? {
          prompt: '점 ㅇ은 원의 중심입니다. 원의 지름은 어느 것일까요?',
          answer: 지름선,
          wrongs: [현선, 반지름선, 안선],
          tag: 'shape',
          concept: '원 위의 두 점을 이은 선분이 원의 중심을 지날 때, 이 선분을 원의 지름이라고 합니다.',
          strategy: '지름의 두 조건 확인하기',
          hint: '두 끝이 모두 원 위에 있는지, 그리고 원의 중심 ㅇ을 지나는지 두 가지를 모두 보세요.',
          steps: [`${지름선}은(는) 두 끝이 원 위에 있고 원의 중심 ㅇ을 지납니다.`, `${현선}은(는) 두 끝이 원 위에 있지만 원의 중심을 지나지 않으므로 지름이 아닙니다.`, `그러므로 지름은 ${지름선}입니다.`],
          misconceptionTip: '원 위의 두 점을 이었다고 모두 지름은 아닙니다. 원의 중심을 지나야 지름입니다.',
          visual,
        }
      : {
          prompt: '점 ㅇ은 원의 중심입니다. 원의 반지름은 어느 것일까요?',
          answer: 반지름선,
          wrongs: [안선, 지름선, 현선],
          tag: 'shape',
          concept: '원의 중심과 원 위의 한 점을 이은 선분을 원의 반지름이라고 합니다.',
          strategy: '반지름의 두 끝 확인하기',
          hint: '한 끝은 원의 중심 ㅇ, 다른 한 끝은 원 위에 있는 선분을 찾으세요.',
          steps: [`${반지름선}은(는) 원의 중심 ㅇ과 원 위의 점 ${반}을(를) 이은 선분입니다.`, `${안선}은(는) 점 ${안이름}이(가) 원 위에 있지 않으므로 반지름이 아닙니다.`, `그러므로 반지름은 ${반지름선}입니다.`],
          misconceptionTip: '원의 중심에서 시작해도 다른 끝이 원 위에 있지 않으면 반지름이 아닙니다.',
          visual,
        };
  },
};

