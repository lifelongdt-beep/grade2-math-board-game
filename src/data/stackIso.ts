// ════════════════════════════════════════════════════════════════════
// 쌓기나무를 비스듬히 내려다본 그림(등각 그림)의 셈
// ────────────────────────────────────────────────────────────────────
// 높이판 h[줄][열]: 줄은 뒤(0)에서 앞으로, 열은 왼쪽(0)에서 오른쪽으로.
// 그림은 앞쪽 오른쪽 위에서 내려다봅니다. 앞면(+y)이 왼쪽 아래, 오른쪽
// 옆면(+x)이 오른쪽 아래, 윗면이 위로 보입니다 — 교과서 그림과 같습니다.
//
// 그림에 보이지 않는 쌓기나무가 있으면 '모두 몇 개'의 답이 하나로
// 정해지지 않습니다. 그래서 어느 쌓기나무가 보이는지 정확히 셉니다.
//
// 등각 그림은 화면을 작은 정삼각형으로 빈틈없이 나눕니다. 쌓기나무
// 하나는 정육각형, 곧 삼각형 여섯 개를 덮습니다. 삼각형 하나를 여러
// 쌓기나무가 덮으면 보는 사람에게 가장 가까운 것(x+y+z가 가장 큰 것)만
// 보입니다. 삼각형을 하나도 차지하지 못한 쌓기나무는 보이지 않습니다.
// ════════════════════════════════════════════════════════════════════

export type 높이판 = number[][];
export type 블록 = { x: number; y: number; z: number };

const 루트3반 = Math.sqrt(3) / 2;

/** 쌓기나무 한 모서리를 1로 볼 때 꼭짓점 (x, y, z)가 그림에 놓이는 자리입니다. */
export const 비추기 = (x: number, y: number, z: number): [number, number] => [(x - y) * 루트3반, (x + y) / 2 - z];

export const 블록들 = (h: 높이판): 블록[] => {
  const 결과: 블록[] = [];
  h.forEach((row, y) => row.forEach((n, x) => {
    for (let z = 0; z < n; z += 1) 결과.push({ x, y, z });
  }));
  return 결과;
};

// 쌓기나무가 덮는 육각형의 가운데는 쌓기나무 한가운데가 비친 자리입니다.
const 가운데 = (b: 블록) => 비추기(b.x + 0.5, b.y + 0.5, b.z + 0.5);
// 가운데에서 본 육각형의 꼭짓점(뾰족한 쪽이 위아래)입니다.
const 꼭짓점들: Array<[number, number]> = [
  [0, -1], [루트3반, -0.5], [루트3반, 0.5], [0, 1], [-루트3반, 0.5], [-루트3반, -0.5],
];
const 안에있나 = (점: [number, number], b: 블록) => {
  const [cx, cy] = 가운데(b);
  const qx = Math.abs(점[0] - cx);
  const qy = Math.abs(점[1] - cy);
  return qx < 루트3반 - 1e-6 && qy + qx / Math.sqrt(3) < 1 - 1e-6;
};

/** 그림에 조금이라도 보이는 쌓기나무입니다. */
export const 보이는블록 = (cubes: 블록[]): 블록[] =>
  cubes.filter((b) => {
    const [cx, cy] = 가운데(b);
    return 꼭짓점들.some((v, i) => {
      const w = 꼭짓점들[(i + 1) % 6];
      const 점: [number, number] = [cx + (v[0] + w[0]) / 3, cy + (v[1] + w[1]) / 3];
      const 깊이 = b.x + b.y + b.z;
      return !cubes.some((o) => o !== b && o.x + o.y + o.z > 깊이 && 안에있나(점, o));
    });
  });

export const 숨은개수 = (h: 높이판) => {
  const cubes = 블록들(h);
  return cubes.length - 보이는블록(cubes).length;
};

/**
 * 그림과 똑같이 보이게 쌓을 때 가장 적게 드는 개수입니다. 보이는
 * 쌓기나무는 모두 있어야 하고, 그 아래는 받쳐 주어야 합니다. 숨은
 * 쌓기나무를 빼도 그림은 그대로입니다(숨은 것은 더 가까운 것에 가려
 * 있고, 그 뒤에 있는 것도 같은 것에 가려 있으므로).
 */
export const 가장적은개수 = (h: 높이판) => 블록들(가장적은모양(h)).length;

export const 가장적은모양 = (h: 높이판): 높이판 => {
  const 높이 = h.map((row) => row.map(() => 0));
  for (const b of 보이는블록(블록들(h))) 높이[b.y][b.x] = Math.max(높이[b.y][b.x], b.z + 1);
  return 높이;
};
