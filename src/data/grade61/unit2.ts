const 전개도: G5Family = {
  id: 'net',
  make: (seed, lv) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 8);
    const s = 사이(next, 2, 9);
    const h = 사이(next, 3, 12);
    const kind = next(lv === '하' ? 2 : 3);
    if (kind === 0) {
      return {
        prompt: `${기둥(n)}의 전개도에서 직사각형 모양의 옆면은 몇 개일까요?`,
        answer: `${n}개`,
        wrongs: [n + 2, 2, n - 1].filter((x) => x !== n).map((x) => `${x}개`),
        tag: 'solid',
        strategy: '각기둥의 전개도 알기',
        hint: '옆면의 수는 밑면의 변의 수와 같아요.',
        steps: [`${기둥(n)}의 옆면은 ${n}개입니다.`],
        visual: 펼친그림(n),
      };
    }
    if (kind === 1) {
      return {
        prompt: `${기둥(n)}의 전개도에는 면이 모두 몇 개 있을까요?`,
        answer: `${n + 2}개`,
        wrongs: [n, n + 1, 3 * n].filter((x) => x !== n + 2).map((x) => `${x}개`),
        tag: 'solid',
        strategy: '각기둥의 전개도 알기',
        hint: '밑면 2개와 옆면을 모두 세어요.',
        steps: [`밑면 2개, 옆면 ${n}개이므로 ${n + 2}개입니다.`],
        visual: 펼친그림(n),
      };
    }
    // 옆면을 이은 직사각형이 실처럼 가늘면 전개도로 알아보기 어렵습니다.
    if (s * n > h * 5) return null;
    return {
      prompt: `밑면이 한 변 ${s} cm인 정${각[n]}각형이고 높이가 ${h} cm인 ${기둥(n)}의 전개도에서, 옆면을 모두 이은 큰 직사각형의 가로는 몇 cm일까요?`,
      answer: `${s * n} cm`,
      wrongs: [s * (n + 2), s + h, h * n, s * (n - 1)].filter((x, i, xs) => x !== s * n && xs.indexOf(x) === i).slice(0, 3).map((x) => `${x} cm`),
      tag: 'solid',
      strategy: '각기둥의 전개도에서 길이 구하기',
      hint: '옆면을 이은 직사각형의 가로는 밑면의 둘레와 같아요.',
      steps: [`밑면의 둘레는 ${s}×${n}=${s * n}이므로 가로는 ${s * n} cm입니다.`],
      visual: 펼친그림(n, s, h, true),
    };
  },
};

const 비교: G5Family = {
  id: 'compare',
  make: (seed) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 8);
    const w = (['면', '모서리', '꼭짓점'] as const)[next(3)];
    const a = 기둥수(n, w);
    const b = 뿔수(n, w);
    return {
      prompt: `${기둥(n)}과(와) ${뿔(n)}의 ${w}의 수의 차는 몇 개일까요?`,
      answer: `${a - b}개`,
      wrongs: [...new Set([a + b, a - b + 1, Math.max(1, a - b - 1), n])].filter((x) => x !== a - b && x > 0).slice(0, 3).map((x) => `${x}개`),
      tag: 'solid',
      strategy: '각기둥과 각뿔 비교하기',
      hint: '두 입체도형의 수를 각각 세어 빼요.',
      steps: [`${기둥(n)}의 ${w}은(는) ${a}개, ${뿔(n)}의 ${w}은(는) ${b}개입니다.`, `${a}-${b}=${a - b}`],
      minusIsOperator: true,
    };
  },
};

