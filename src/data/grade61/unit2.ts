// ════════════════════════════════════════════════════════════════════
// 6-1 2단원 각기둥과 각뿔
// ────────────────────────────────────────────────────────────────────
// 지도서 차시 차례: 단원 도입 / 각기둥 ⑴(밑면, 옆면) / 각기둥 ⑵(이름,
// 모서리, 꼭짓점, 높이) / 각기둥의 전개도 / 각뿔 ⑴(밑면, 옆면) / 각뿔 ⑵
//
// 지도서가 못박은 것:
//   · 각기둥: 서로 평행한 두 면이 합동인 다각형이고 옆면이 모두 직사각형인
//     입체도형. 밑면은 놓인 방향에 따라 달라지지 않습니다.
//   · 각뿔: 밑면이 다각형이고 옆면이 모두 삼각형인 입체도형. 밑면은 1개.
//   · 이름은 밑면의 모양으로 짓습니다(삼각기둥, 오각뿔 …).
//
// 수 세기(n각기둥: 면 n+2, 모서리 3n, 꼭짓점 2n / n각뿔: 면 n+1,
// 모서리 2n, 꼭짓점 n+1)는 식이 아니라 밑면·옆면을 세어 구하게 풀이를
// 적습니다.
// ════════════════════════════════════════════════════════════════════

const 각 = ['', '', '', '삼', '사', '오', '육', '칠', '팔', '구', '십'];
const 기둥 = (n: number) => `${각[n]}각기둥`;
const 뿔 = (n: number) => `${각[n]}각뿔`;

type 무엇 = '면' | '모서리' | '꼭짓점';
const 기둥수 = (n: number, w: 무엇) => (w === '면' ? n + 2 : w === '모서리' ? 3 * n : 2 * n);
const 뿔수 = (n: number, w: 무엇) => (w === '면' ? n + 1 : w === '모서리' ? 2 * n : n + 1);

// 겨냥도입니다. 수 세기 문항은 그림을 보며 밑면·옆면을 세어 보게 합니다.
const 겨냥도 = (종류: '기둥' | '뿔', n: number): SolidFigureVisual => ({
  kind: 'solid-figure',
  label: 종류 === '기둥' ? 기둥(n) : 뿔(n),
  solid: 종류 === '기둥' ? 'prism' : 'pyramid',
  sides: n,
});

// 각기둥의 전개도입니다. 길이를 주지 않는 문항은 비율만 보기 좋게 둡니다.
const 펼친그림 = (n: number, s = 1, h = 1.6, 길이 = false): SolidNetVisual => ({
  kind: 'solid-net',
  label: `${기둥(n)}의 전개도`,
  solid: 'prism',
  sides: n,
  base: s,
  height: h,
  ...(길이 ? { labels: { base: `${s} cm`, height: `${h} cm`, width: '? cm' } } : {}),
});

const 수세기 = (종류: '기둥' | '뿔'): G5Family => ({
  id: `count-${종류}`,
  make: (seed, lv) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, lv === '상' ? 10 : 7);
    const w = (['면', '모서리', '꼭짓점'] as const)[next(3)];
    const 이름 = 종류 === '기둥' ? 기둥(n) : 뿔(n);
    const v = 종류 === '기둥' ? 기둥수(n, w) : 뿔수(n, w);
    const 다른것 = (['면', '모서리', '꼭짓점'] as const).map((x) => (종류 === '기둥' ? 기둥수(n, x) : 뿔수(n, x)));
    const wrongs = [...new Set([...다른것, 종류 === '기둥' ? 뿔수(n, w) : 기둥수(n, w), v + 1, v - 1, n])].filter((x) => x > 0 && x !== v);
    const 풀이 =
      종류 === '기둥'
        ? {
            면: `밑면 2개와 옆면 ${n}개이므로 ${n}+2=${n + 2}개입니다.`,
            모서리: `한 밑면에 ${n}개씩 두 밑면에 ${n * 2}개, 옆에 ${n}개이므로 ${n}×3=${3 * n}개입니다.`,
            꼭짓점: `한 밑면에 ${n}개씩 두 밑면에 있으므로 ${n}×2=${2 * n}개입니다.`,
          }
        : {
            면: `밑면 1개와 옆면 ${n}개이므로 ${n}+1=${n + 1}개입니다.`,
            모서리: `밑면에 ${n}개, 각뿔의 꼭짓점으로 모이는 것이 ${n}개이므로 ${n}×2=${2 * n}개입니다.`,
            꼭짓점: `밑면에 ${n}개, 각뿔의 꼭짓점 1개이므로 ${n}+1=${n + 1}개입니다.`,
          };
    return {
      prompt: `${이름}의 ${w}은(는) 몇 개일까요?`,
      answer: `${v}개`,
      wrongs: wrongs.slice(0, 4).map((x) => `${x}개`),
      tag: 'solid',
      strategy: `${종류 === '기둥' ? '각기둥' : '각뿔'}의 구성 요소 세기`,
      hint: 종류 === '기둥' ? '밑면은 2개, 옆면은 밑면의 변의 수만큼 있어요.' : '밑면은 1개, 옆면은 밑면의 변의 수만큼 있어요.',
      steps: [풀이[w]],
      misconceptionTip: 종류 === '기둥' ? '각기둥은 밑면이 2개라는 것을 잊지 마세요.' : '각뿔은 밑면이 1개뿐이에요.',
      visual: 겨냥도(종류, n),
    };
  },
});

const 이름알기 = (종류: '기둥' | '뿔'): G5Family => ({
  id: `name-${종류}`,
  make: (seed) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 8);
    const kind = next(3);
    const 이름 = 종류 === '기둥' ? 기둥(n) : 뿔(n);
    if (kind === 0) {
      return {
        prompt: `밑면의 모양이 ${각[n]}각형인 ${종류 === '기둥' ? '각기둥' : '각뿔'}의 이름은 무엇일까요?`,
        answer: 이름,
        wrongs: [종류 === '기둥' ? 뿔(n) : 기둥(n), 종류 === '기둥' ? 기둥(n + 1) : 뿔(n + 1), 종류 === '기둥' ? 기둥(n - 1 >= 3 ? n - 1 : n + 2) : 뿔(n - 1 >= 3 ? n - 1 : n + 2)],
        tag: 'solid',
        strategy: '밑면의 모양으로 이름 짓기',
        hint: '이름은 밑면의 모양에 따라 정해져요.',
        steps: [`밑면이 ${각[n]}각형이므로 ${이름}입니다.`],
      };
    }
    if (kind === 1) {
      const 옆 = n;
      return {
        prompt: `옆면이 ${옆}개인 ${종류 === '기둥' ? '각기둥' : '각뿔'}의 이름은 무엇일까요?`,
        answer: 이름,
        wrongs: [종류 === '기둥' ? 기둥(n + 2 <= 10 ? n + 2 : n - 2) : 뿔(n + 1), 종류 === '기둥' ? 뿔(n) : 기둥(n), 종류 === '기둥' ? 기둥(n - 1 >= 3 ? n - 1 : n + 1) : 뿔(n - 1 >= 3 ? n - 1 : n + 2)],
        tag: 'solid',
        strategy: '옆면의 수로 이름 알기',
        hint: '옆면의 수는 밑면의 변의 수와 같아요.',
        steps: [`옆면이 ${옆}개이면 밑면은 ${각[n]}각형이므로 ${이름}입니다.`],
      };
    }
    const 면 = 종류 === '기둥' ? n + 2 : n + 1;
    return {
      prompt: `면이 모두 ${면}개인 ${종류 === '기둥' ? '각기둥' : '각뿔'}의 이름은 무엇일까요?`,
      answer: 이름,
      wrongs: 종류 === '기둥' ? [기둥(n + 2 <= 10 ? n + 2 : n - 2), 기둥(n + 1), 뿔(n + 1)] : [뿔(n + 1), 기둥(n - 1 >= 3 ? n - 1 : n + 2), 뿔(n - 1 >= 3 ? n - 1 : n + 2)],
      tag: 'solid',
      strategy: '면의 수로 이름 알기',
      hint: 종류 === '기둥' ? '면의 수에서 밑면 2개를 빼면 옆면의 수예요.' : '면의 수에서 밑면 1개를 빼면 옆면의 수예요.',
      steps: [`옆면은 ${면}-${종류 === '기둥' ? 2 : 1}=${n}개이므로 밑면은 ${각[n]}각형입니다.`, `그러므로 ${이름}입니다.`],
      minusIsOperator: true,
    };
  },
});

