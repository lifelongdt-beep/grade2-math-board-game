import type { Difficulty } from '../../types';
import type { G5Family } from '../grade5/build';
import { 고르개, 사이 } from '../grade11/common';

// ════════════════════════════════════════════════════════════════════
// 6-1 2단원 각기둥과 각뿔
// ────────────────────────────────────────────────────────────────────
// 지도서 차시 차례: 단원 도입 / 각기둥 ⑴(밑면, 옆면) / 각기둥 ⑵(이름,
// 모서리, 꼭짓점, 높이) / 각기둥의 전개도 / 각뿔 ⑴(밑면, 옆면) / 각뿔 ⑵
//
// 지도서가 못박은 것:
//   · 각기둥: 서로 평행한 두 면이 합동인 다각형이고 옆면이 모두 직사각형인
//     입체도형. 밑면은 놓인 방향에 따라 달라지지 않습니다.
//   · 각뿔: 밑면이 다각형이고 옆면이 모두 삼각형인 입체도형. 밑면은 1개.
//   · 이름은 밑면의 모양으로 짓습니다(삼각기둥, 오각뿔 …).
//
// 수 세기(n각기둥: 면 n+2, 모서리 3n, 꼭짓점 2n / n각뿔: 면 n+1,
// 모서리 2n, 꼭짓점 n+1)는 식이 아니라 밑면·옆면을 세어 구하게 풀이를
// 적습니다.
// ════════════════════════════════════════════════════════════════════

const 각 = ['', '', '', '삼', '사', '오', '육', '칠', '팔', '구', '십'];
const 기둥 = (n: number) => `${각[n]}각기둥`;
const 뿔 = (n: number) => `${각[n]}각뿔`;

type 무엇 = '면' | '모서리' | '꼭짓점';
const 기둥수 = (n: number, w: 무엇) => (w === '면' ? n + 2 : w === '모서리' ? 3 * n : 2 * n);
const 뿔수 = (n: number, w: 무엇) => (w === '면' ? n + 1 : w === '모서리' ? 2 * n : n + 1);

const 수세기 = (종류: '기둥' | '뿔'): G5Family => ({
  id: `count-${종류}`,
  make: (seed, lv) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, lv === '상' ? 10 : 7);
    const w = (['면', '모서리', '꼭짓점'] as const)[next(3)];
    const 이름 = 종류 === '기둥' ? 기둥(n) : 뿔(n);
    const v = 종류 === '기둥' ? 기둥수(n, w) : 뿔수(n, w);
    const 다른것 = (['면', '모서리', '꼭짓점'] as const).map((x) => (종류 === '기둥' ? 기둥수(n, x) : 뿔수(n, x)));
    const wrongs = [...new Set([...다른것, 종류 === '기둥' ? 뿔수(n, w) : 기둥수(n, w), v + 1, v - 1, n])].filter((x) => x > 0 && x !== v);
    const 풀이 =
      종류 === '기둥'
        ? {
            면: `밑면 2개와 옆면 ${n}개이므로 ${n}+2=${n + 2}개입니다.`,
            모서리: `한 밑면에 ${n}개씩 두 밑면에 ${n * 2}개, 옆에 ${n}개이므로 ${n}×3=${3 * n}개입니다.`,
            꼭짓점: `한 밑면에 ${n}개씩 두 밑면에 있으므로 ${n}×2=${2 * n}개입니다.`,
          }
        : {
            면: `밑면 1개와 옆면 ${n}개이므로 ${n}+1=${n + 1}개입니다.`,
            모서리: `밑면에 ${n}개, 각뿔의 꼭짓점으로 모이는 것이 ${n}개이므로 ${n}×2=${2 * n}개입니다.`,
            꼭짓점: `밑면에 ${n}개, 각뿔의 꼭짓점 1개이므로 ${n}+1=${n + 1}개입니다.`,
          };
    return {
      prompt: `${이름}의 ${w}은(는) 몇 개일까요?`,
      answer: `${v}개`,
      wrongs: wrongs.slice(0, 4).map((x) => `${x}개`),
      tag: 'solid',
      strategy: `${종류 === '기둥' ? '각기둥' : '각뿔'}의 구성 요소 세기`,
      hint: 종류 === '기둥' ? '밑면은 2개, 옆면은 밑면의 변의 수만큼 있어요.' : '밑면은 1개, 옆면은 밑면의 변의 수만큼 있어요.',
      steps: [풀이[w]],
      misconceptionTip: 종류 === '기둥' ? '각기둥은 밑면이 2개라는 것을 잊지 마세요.' : '각뿔은 밑면이 1개뿐이에요.',
    };
  },
});

const 이름알기 = (종류: '기둥' | '뿔'): G5Family => ({
  id: `name-${종류}`,
  make: (seed) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 8);
    const kind = next(3);
    const 이름 = 종류 === '기둥' ? 기둥(n) : 뿔(n);
    if (kind === 0) {
      return {
        prompt: `밑면의 모양이 ${각[n]}각형인 ${종류 === '기둥' ? '각기둥' : '각뿔'}의 이름은 무엇일까요?`,
        answer: 이름,
        wrongs: [종류 === '기둥' ? 뿔(n) : 기둥(n), 종류 === '기둥' ? 기둥(n + 1) : 뿔(n + 1), 종류 === '기둥' ? 기둥(n - 1 >= 3 ? n - 1 : n + 2) : 뿔(n - 1 >= 3 ? n - 1 : n + 2)],
        tag: 'solid',
        strategy: '밑면의 모양으로 이름 짓기',
        hint: '이름은 밑면의 모양에 따라 정해져요.',
        steps: [`밑면이 ${각[n]}각형이므로 ${이름}입니다.`],
      };
    }
    if (kind === 1) {
      const 옆 = n;
      return {
        prompt: `옆면이 ${옆}개인 ${종류 === '기둥' ? '각기둥' : '각뿔'}의 이름은 무엇일까요?`,
        answer: 이름,
        wrongs: [종류 === '기둥' ? 기둥(n + 2 <= 10 ? n + 2 : n - 2) : 뿔(n + 1), 종류 === '기둥' ? 뿔(n) : 기둥(n), 종류 === '기둥' ? 기둥(n - 1 >= 3 ? n - 1 : n + 1) : 뿔(n - 1 >= 3 ? n - 1 : n + 2)],
        tag: 'solid',
        strategy: '옆면의 수로 이름 알기',
        hint: '옆면의 수는 밑면의 변의 수와 같아요.',
        steps: [`옆면이 ${옆}개이면 밑면은 ${각[n]}각형이므로 ${이름}입니다.`],
      };
    }
    const 면 = 종류 === '기둥' ? n + 2 : n + 1;
    return {
      prompt: `면이 모두 ${면}개인 ${종류 === '기둥' ? '각기둥' : '각뿔'}의 이름은 무엇일까요?`,
      answer: 이름,
      wrongs: 종류 === '기둥' ? [기둥(n + 2 <= 10 ? n + 2 : n - 2), 기둥(n + 1), 뿔(n + 1)] : [뿔(n + 1), 기둥(n - 1 >= 3 ? n - 1 : n + 2), 뿔(n - 1 >= 3 ? n - 1 : n + 2)],
      tag: 'solid',
      strategy: '면의 수로 이름 알기',
      hint: 종류 === '기둥' ? '면의 수에서 밑면 2개를 빼면 옆면의 수예요.' : '면의 수에서 밑면 1개를 빼면 옆면의 수예요.',
      steps: [`옆면은 ${면}-${종류 === '기둥' ? 2 : 1}=${n}개이므로 밑면은 ${각[n]}각형입니다.`, `그러므로 ${이름}입니다.`],
      minusIsOperator: true,
    };
  },
});

const 뜻 = (어느?: '기둥' | '뿔'): G5Family => ({
  id: `definition-${어느 ?? 'all'}`,
  make: (seed) => {
    const qs = [
      { p: '각기둥에서 서로 평행하고 합동인 두 면을 무엇이라고 할까요?', a: '밑면', w: ['옆면', '모서리', '꼭짓점'], s: '각기둥에서 서로 평행하고 합동인 두 면을 밑면이라고 합니다.' },
      { p: '각기둥의 옆면은 어떤 모양일까요?', a: '직사각형', w: ['삼각형', '원', '오각형'], s: '각기둥의 옆면은 모두 직사각형입니다.' },
      { p: '각뿔의 옆면은 어떤 모양일까요?', a: '삼각형', w: ['직사각형', '원', '오각형'], s: '각뿔의 옆면은 모두 삼각형입니다.' },
      { p: '각뿔의 밑면은 몇 개일까요?', a: '1개', w: ['2개', '3개', '없습니다'], s: '각뿔의 밑면은 1개입니다.' },
      { p: '각기둥의 밑면은 몇 개일까요?', a: '2개', w: ['1개', '3개', '옆면의 수만큼'], s: '각기둥은 서로 평행하고 합동인 밑면이 2개입니다.' },
      { p: '각기둥에서 두 밑면 사이의 거리를 무엇이라고 할까요?', a: '높이', w: ['모서리', '밑면', '옆면'], s: '두 밑면 사이의 거리를 높이라고 합니다.' },
      { p: '각뿔에서 옆면이 모두 만나는 점을 무엇이라고 할까요?', a: '각뿔의 꼭짓점', w: ['밑면', '모서리', '높이'], s: '옆면이 모두 만나는 점을 각뿔의 꼭짓점이라고 합니다.' },
      { p: '각기둥을 옆으로 눕혀 놓으면 밑면은 어떻게 될까요?', a: '그대로입니다', w: ['옆면으로 바뀝니다', '없어집니다', '3개가 됩니다'], s: '밑면은 놓인 방향에 따라 달라지지 않습니다. 서로 평행하고 합동인 두 면이 밑면입니다.' },
    ];
    const 고른 = 어느 ? qs.filter((q) => q.p.includes('각뿔') === (어느 === '뿔')) : qs;
    const q = 고른[seed % 고른.length];
    return { prompt: q.p, answer: q.a, wrongs: q.w, tag: 'solid', strategy: '각기둥과 각뿔의 뜻', hint: '밑면과 옆면의 모양을 떠올려 보세요.', steps: [q.s] };
  },
});

const 전개도: G5Family = {
  id: 'net',
  make: (seed, lv) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 8);
    const s = 사이(next, 2, 9);
    const h = 사이(next, 3, 12);
    const kind = next(lv === '하' ? 2 : 3);
    if (kind === 0) {
      return {
        prompt: `${기둥(n)}의 전개도에서 직사각형 모양의 옆면은 몇 개일까요?`,
        answer: `${n}개`,
        wrongs: [n + 2, 2, n - 1].filter((x) => x !== n).map((x) => `${x}개`),
        tag: 'solid',
        strategy: '각기둥의 전개도 알기',
        hint: '옆면의 수는 밑면의 변의 수와 같아요.',
        steps: [`${기둥(n)}의 옆면은 ${n}개입니다.`],
      };
    }
    if (kind === 1) {
      return {
        prompt: `${기둥(n)}의 전개도에는 면이 모두 몇 개 있을까요?`,
        answer: `${n + 2}개`,
        wrongs: [n, n + 1, 3 * n].filter((x) => x !== n + 2).map((x) => `${x}개`),
        tag: 'solid',
        strategy: '각기둥의 전개도 알기',
        hint: '밑면 2개와 옆면을 모두 세어요.',
        steps: [`밑면 2개, 옆면 ${n}개이므로 ${n + 2}개입니다.`],
      };
    }
    return {
      prompt: `밑면이 한 변 ${s} cm인 정${각[n]}각형이고 높이가 ${h} cm인 ${기둥(n)}의 전개도에서, 옆면을 모두 이은 큰 직사각형의 가로는 몇 cm일까요?`,
      answer: `${s * n} cm`,
      wrongs: [s * (n + 2), s + h, h * n, s * (n - 1)].filter((x, i, xs) => x !== s * n && xs.indexOf(x) === i).slice(0, 3).map((x) => `${x} cm`),
      tag: 'solid',
      strategy: '각기둥의 전개도에서 길이 구하기',
      hint: '옆면을 이은 직사각형의 가로는 밑면의 둘레와 같아요.',
      steps: [`밑면의 둘레는 ${s}×${n}=${s * n}이므로 가로는 ${s * n} cm입니다.`],
    };
  },
};

const 비교: G5Family = {
  id: 'compare',
  make: (seed) => {
    const next = 고르개(seed);
    const n = 사이(next, 3, 8);
    const w = (['면', '모서리', '꼭짓점'] as const)[next(3)];
    const a = 기둥수(n, w);
    const b = 뿔수(n, w);
    return {
      prompt: `${기둥(n)}과(와) ${뿔(n)}의 ${w}의 수의 차는 몇 개일까요?`,
      answer: `${a - b}개`,
      wrongs: [...new Set([a + b, a - b + 1, Math.max(1, a - b - 1), n])].filter((x) => x !== a - b && x > 0).slice(0, 3).map((x) => `${x}개`),
      tag: 'solid',
      strategy: '각기둥과 각뿔 비교하기',
      hint: '두 입체도형의 수를 각각 세어 빼요.',
      steps: [`${기둥(n)}의 ${w}은(는) ${a}개, ${뿔(n)}의 ${w}은(는) ${b}개입니다.`, `${a}-${b}=${a - b}`],
      minusIsOperator: true,
    };
  },
};

export const unit2Lesson61 = (lessonNo: number, lv: Difficulty): G5Family[] | null => {
  switch (lessonNo) {
    case 1:
      return [뜻(), 이름알기('기둥')];
    case 2:
      return [뜻('기둥'), 이름알기('기둥')];
    case 3:
      return lv === '하' ? [수세기('기둥'), 이름알기('기둥')] : [수세기('기둥'), 이름알기('기둥'), 뜻('기둥')];
    case 4:
      return [전개도];
    case 5:
      return [뜻('뿔'), 이름알기('뿔')];
    case 6:
      return lv === '상' ? [수세기('뿔'), 비교] : [수세기('뿔'), 이름알기('뿔')];
    default:
      return null;
  }
};
