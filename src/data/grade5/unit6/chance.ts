// ────────────────────────────────────────────────────────────────────
// 지도서가 못박아 둔 것이 둘 있습니다.
//   · 쓰는 말은 다섯입니다 — 불가능하다 / ~아닐 것 같다 / 반반이다 /
//     ~일 것 같다 / 확실하다. 다른 말은 쓰지 않습니다.
//   · 7차시에서 수로 나타내는 것은 0, 1/2, 1뿐입니다("가능성이 직관적으로
//     파악되는 상황들을 제시하여 일이 일어날 가능성을 0, 1/2, 1의 수로
//     나타내어 보게 한다"). 1/6이나 1/3은 아직 다루지 않습니다.
// 그래서 수로 묻는 문항은 값이 0, 1/2, 1인 상황만 고릅니다. 그 확인은
// core.ts의 수로()가 합니다 — 셋이 아니면 null을 돌려주고, 문항을
// 만들지 않습니다.
// ════════════════════════════════════════════════════════════════════

type 상황 = { 글: string; 값: 가능성; visual?: QuestionVisual };

const 색들: ChanceColor[] = ['red', 'blue', 'yellow'];

/** 회전판 하나와, 그 판에서 한 색에 멈출 가능성입니다. */
const 회전판상황 = (seed: number, 반만: boolean): 상황 => {
  const next = rand(seed);
  const 모양 = 반만 ? next(3) : next(6);
  const 판: ChanceColor[][] = [
    ['red'],                                   // 전부 빨강 → 빨강 1, 파랑 0
    ['red', 'blue'],                           // 반반
    ['red', 'red', 'blue', 'blue'],            // 반반
    ['red', 'blue', 'yellow'],                 // 1/3씩
    ['red', 'red', 'red', 'blue'],             // 3/4, 1/4
    ['red', 'blue', 'blue', 'blue'],           // 1/4, 3/4
  ];
  const slices = 판[모양];
  const 물을색 = 색들[next(색들.length)];
  return {
    글: `화살이 ${eul(색이름[물을색])} 가리킬`,
    값: 세어보기(slices, 물을색),
    visual: 회전판그림('회전판', [{ slices }]),
  };
};

/** 주머니 하나와, 거기서 한 색 바둑돌이 나올 가능성입니다. */
const 주머니상황 = (seed: number, 반만: boolean): 상황 => {
  const next = rand(seed);
  const 모양 = 반만 ? next(3) : next(5);
  const 담긴것: ChanceColor[][] = [
    ['black', 'black', 'black'],
    ['black', 'white'],
    ['black', 'black', 'white', 'white'],
    ['black', 'white', 'white', 'white'],
    ['black', 'black', 'black', 'white'],
  ];
  const marbles = 담긴것[모양];
  const 물을색: ChanceColor = next(2) === 0 ? 'black' : 'white';
  return {
    글: `${iJosa(색이름[물을색])} 나올`,
    값: 세어보기(marbles, 물을색),
    visual: 주머니그림('주머니', [{ marbles }]),
  };
};

