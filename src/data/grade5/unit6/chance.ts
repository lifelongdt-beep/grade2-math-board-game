// 다섯 말 가운데 오답 셋입니다. 씨앗마다 다르게 고르면, 글도 그림도
// 똑같은 문항이 보기만 바꾸어 한 차시에 두 번 나옵니다. 그래서 답에서
// 가까운 셋으로 못박습니다 — 가까운 말일수록 가려내기 어려우므로
// 문항으로도 이쪽이 낫습니다.
const 다른말들 = (답: string) => {
  const 답자리 = 가능성말들.indexOf(답 as (typeof 가능성말들)[number]);
  return 가능성말들
    .map((말, 자리) => ({ 말, 거리: Math.abs(자리 - 답자리), 자리 }))
    .filter((one) => one.말 !== 답)
    .sort((a, b) => a.거리 - b.거리 || a.자리 - b.자리)
    .slice(0, 3)
    .map((one) => one.말);
};

const 까닭 = ({ 바라는것, 전체 }: 가능성) => {
  if (바라는것 === 0) return `바라는 경우가 하나도 없으므로 일어날 수 없습니다.`;
  if (바라는것 === 전체) return `모든 경우가 바라는 경우이므로 반드시 일어납니다.`;
  if (바라는것 * 2 === 전체) return `${전체}가지 가운데 ${바라는것}가지이므로 꼭 반입니다.`;
  return 바라는것 * 2 < 전체
    ? `${전체}가지 가운데 ${바라는것}가지뿐이므로 반보다 적습니다.`
    : `${전체}가지 가운데 ${바라는것}가지이므로 반보다 많습니다.`;
};

