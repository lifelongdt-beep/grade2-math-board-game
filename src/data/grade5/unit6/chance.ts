// ── 6차시 일이 일어날 가능성을 어떻게 비교할까요 ────────────────────

const 비교판들 = (seed: number) => {
  const next = rand(seed);
  // 빨간색 칸 수가 서로 다른 회전판 셋을 만듭니다. 칸 수를 같게 두면
  // 가장 높은 것이 하나로 정해집니다.
  const 전체칸 = 4;
  const 고른것 = [
    [0, 2, 4],
    [1, 2, 4],
    [0, 1, 3],
    [1, 3, 4],
    [0, 3, 4],
    [0, 2, 3],
  ][next(6)];
  const 섞은 = [...고른것];
  for (let at = 섞은.length - 1; at > 0; at -= 1) {
    const to = next(at + 1);
    [섞은[at], 섞은[to]] = [섞은[to], 섞은[at]];
  }
  const 이름 = ['가', '나', '다'];
  const items = 섞은.map((빨강, at) => ({
    name: 이름[at],
    slices: [
      ...Array<ChanceColor>(빨강).fill('red'),
      ...Array<ChanceColor>(전체칸 - 빨강).fill('blue'),
    ],
  }));
  return { items, 빨강수: 섞은, 이름, 전체칸 };
};

