import type { Difficulty } from '../../types';
import type { G5Spec } from './build';

// ════════════════════════════════════════════════════════════════════
// 하·중·상은 '생각하는 방식'으로 나눕니다
// ────────────────────────────────────────────────────────────────────
// 1·3·4·5·6학년은 하·중·상에서 같은 뭉치를 같은 범위의 수로 불러,
// 수준을 바꾸어도 같은 결의 문제가 나왔습니다(6-1 3단원은 '상'에
// 2.22÷3이, '하'에 4.48÷8이 나왔습니다).
//
// 수준은 수를 크게 해서 억지로 어렵게 만드는 것이 아닙니다.
//   하(지식) — 단순한 지식을 묻습니다. 뜻·이름 알기, 바로 계산하기.
//   중(적용) — 약간의 고민이 필요합니다. 문장으로 된 상황에 적용하기,
//             길을 짚어 준 계산 과정 따라가기.
//   상(사고) — 고차적인 사고력이 필요합니다. 풀이 과정과 까닭을 따지기,
//             잘못을 찾아 바로잡기, 거꾸로 생각하기, 수학 용어를 바르게
//             쓴 말 고르기, 생활 속 상황에 응용하기.
// 문항 하나하나의 답과 풀이는 그대로 두고, 어떤 문항을 낼지만 고릅니다.
// ════════════════════════════════════════════════════════════════════

export type 사고단계 = 0 | 1 | 2;

const 문장수 = (글: string) => 글.split(/[.?!]\s/).filter((one) => one.trim().length > 4).length;
const 수개수 = (글: string) => (글.match(/\d+(?:\.\d+)?(?:\/\d+)?/g) ?? []).length;

/** 문항이 묻는 생각의 결입니다. 0 지식, 1 적용, 2 사고. */
export const 사고단계 = (spec: Pick<G5Spec, 'prompt' | 'strategy'>): 사고단계 => {
  const 글 = spec.prompt;
  const 갈래 = spec.strategy ?? '';
  // 사고: 과정·까닭 따지기, 잘못 찾기, 거꾸로, 용어를 바르게 쓴 말, 여러 조건 견주기
  if (/까닭|이유|왜 그런지|설명으로 (옳|알맞|바르)|바르게 (말한|설명한|읽은)|잘못|틀리게|틀린 곳|바르게 고/.test(글)) return 2;
  if (/옳은 것을 모두|옳지 않은 것을 모두|모두 고른|반드시 맞는/.test(글)) return 2;
  if (/어떤 수|거꾸로|처음에 있던|들어갈 수 있는|될 수 없는|적어도|최대|최소|몇 가지/.test(글)) return 2;
  if (/수 카드|가장 큰 .*만들|가장 작은 .*만들/.test(글)) return 2;
  if (/거꾸로|잘못|까닭|판단|추론|견주어 고르기/.test(갈래)) return 2;
  // 생활 속 응용: 조건이 여럿인 긴 상황 문장
  if (문장수(글) >= 3 && 수개수(글) >= 3 && !/과정입니다/.test(글)) return 2;
  // 지식: 짧은 한 문장으로 뜻·이름·바로 계산을 묻습니다.
  if (문장수(글) <= 1 && 수개수(글) <= 2 && !/과정입니다/.test(글)) return 0;
  if (/^(그림|다음|아래)[^.]*(무엇|어느 것|몇 개)일까요\?$/.test(글) && 수개수(글) <= 2) return 0;
  return 1;
};

// 0이 아닌 숫자의 개수입니다. 400×30은 2개, 398×91은 5개.
const 숫자무게 = (token: string) => {
  const [정수, 소수 = ''] = token.split('.');
  return [...정수].filter((d) => d !== '0').length + Math.max(0, 정수.length - 1) * 0.3 + 소수.length * 1.5;
};

/** 수가 얼마나 다루기 번거로운지입니다. 하에서 쉬운 수를 고르는 데만 씁니다. */
export const 수번거로움 = (spec: Pick<G5Spec, 'prompt'>): number => {
  let 점수 = 0;
  const 분수빼고 = spec.prompt.replace(/(\d+)\/(\d+)/g, (_, 분자: string, 분모: string) => {
    점수 += 1 + Math.log2(Number(분모)) * 0.6 + 숫자무게(분자) * 0.4;
    return ' ';
  });
  for (const 수 of 분수빼고.match(/\d+(?:\.\d+)?/g) ?? []) 점수 += 숫자무게(수);
  return 점수;
};

/** 수준끼리 견주는 한 줄 점수입니다(사고의 결이 먼저, 수는 덤). */
export const 난도점수 = (spec: Pick<G5Spec, 'prompt' | 'strategy'>): number => 사고단계(spec) * 10 + Math.min(9, 수번거로움(spec) * 0.3);

/** 수준마다 뭉치를 얼마나 바라는지(0~1)입니다. t는 이 차시에서 그 뭉치의 사고 차례(0 지식, 1 사고)입니다. */
export const 뭉치선호 = (difficulty: Difficulty, t: number) =>
  // 중은 어느 뭉치도 쉬게 하지 않습니다. 가운데 뭉치에 조금 더 줄 뿐입니다.
  difficulty === '하' ? 1 - t : difficulty === '상' ? t : 0.6 + 0.4 * (1 - Math.abs(t - 0.5) * 2);

/**
 * 같은 뭉치에서 씨앗만 다른 후보 가운데 수준에 맞는 하나를 고릅니다.
 *   하 — 지식형을 먼저, 그 가운데 수가 가장 쉬운 것
 *   중 — 적용형을 먼저, 수는 가운데
 *   상 — 사고형을 먼저, 수는 가운데(수를 크게 해서 어렵게 하지 않습니다)
 */
export const 후보고르기 = <T,>(후보: Array<{ 단계: 사고단계; 수: number; 값: T }>, difficulty: Difficulty): T | null => {
  if (!후보.length) return null;
  const 바라는단계 = difficulty === '하' ? 0 : difficulty === '중' ? 1 : 2;
  const 가까운 = Math.min(...후보.map((one) => Math.abs(one.단계 - 바라는단계)));
  const 남은 = 후보.filter((one) => Math.abs(one.단계 - 바라는단계) === 가까운).sort((a, b) => a.수 - b.수);
  if (difficulty === '하') return 남은[0].값;
  // 상은 가운데보다 조금 위를 고릅니다. 같은 결의 후보뿐일 때 하와 같은 문항이 겹치지 않게.
  return 남은[Math.floor((남은.length - 1) * (difficulty === '상' ? 0.75 : 0.5))].값;
};
