// ════════════════════════════════════════════════════════════════════
// 합동·대칭인 도형을 그리는 과정 (5-2 3단원 3·5·7차시)
// ────────────────────────────────────────────────────────────────────
// '그리는 방법은 무엇일까요'를 글로만 물으면 문장을 외웠는지를 봅니다.
// 여기서는 모눈 위에 반쪽(또는 처음 도형)을 그려 두고, 그리는 과정의
// 한 걸음을 직접 해 보게 합니다.
//   · 대응점을 어디에 찍어야 할까요(가·나·다·라 가운데)
//   · 대응점은 대칭축(중심)에서 어느 쪽으로 몇 칸일까요
//   · 지금까지 그렸습니다. 다음에 할 일은 무엇일까요
//   · 친구가 그린 그림에서 잘못 찍은 점은 무엇일까요
// 오답 자리는 지도서가 적어 둔 실수에서 고릅니다 — 칸을 하나 더(덜)
// 센 자리, 대칭축에 수직이 아닌 자리, 그리고 점대칭을 그려야 하는데
// 선대칭으로 뒤집은 자리(오개념 ④)입니다.
//
// 모든 좌표는 모눈의 점(가로 x, 세로 y, 아래로 갈수록 y가 큼)입니다.
// 답은 그림에 넣은 좌표에서 계산하고, 시험(drawing.check.test.ts)이
// 그림만 보고 다시 계산해 맞춰 봅니다.
// ════════════════════════════════════════════════════════════════════

type 점 = [number, number];
const 같은점 = (a: 점, b: 점) => a[0] === b[0] && a[1] === b[1];
const 가나다라 = ['가', '나', '다', '라'];
const 열 = 10;
const 줄 = 8;

const 섞기 = <T,>(items: T[], next: (n: number) => number): T[] => {
  const out = [...items];
  for (let at = out.length - 1; at > 0; at -= 1) {
    const to = next(at + 1);
    [out[at], out[to]] = [out[to], out[at]];
  }
  return out;
};

const 한줄인가 = (a: 점, b: 점, c: 점) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]) === 0;
const 꺾인곳없음 = (ps: 점[]) => ps.slice(2).some((p, k) => 한줄인가(ps[k], ps[k + 1], p));

export const 방향말 = (dx: number, dy: number) =>
  [dx ? `${dx > 0 ? '오른쪽' : '왼쪽'}으로 ${Math.abs(dx)}칸` : '', dy ? `${dy > 0 ? '아래쪽' : '위쪽'}으로 ${Math.abs(dy)}칸` : '']
    .filter(Boolean)
    .join(', ');

/**
 * 선대칭도형의 오른쪽 반쪽. 첫 점과 끝 점이 대칭축(x = 5) 위에 있고,
 * 사이의 점은 위에서 아래로 차례대로 내려가며 축 오른쪽에 있습니다.
 * 그래서 반쪽과 그 대응이 서로 엇갈리지 않습니다.
 */
const 선대칭반쪽 = (next: (n: number) => number, 사이수: number): 점[] | null => {
  const 축 = 열 / 2;
  for (let 번 = 0; 번 < 20; 번 += 1) {
    const ys = 섞기([0, 1, 2, 3, 4, 5, 6, 7, 8], next).slice(0, 사이수 + 2).sort((a, b) => a - b);
    const ps: 점[] = ys.map((y, k) => [k === 0 || k === ys.length - 1 ? 축 : 축 + 1 + next(4), y]);
    if (!꺾인곳없음(ps)) return ps;
  }
  return null;
};

/**
 * 점대칭도형의 위쪽 반쪽. 첫 점과 끝 점이 대칭의 중심(5, 4)을 사이에 두고
 * 마주 보며, 사이의 점은 왼쪽에서 오른쪽으로 가며 중심보다 위에 있습니다.
 */
const 점대칭반쪽 = (next: (n: number) => number, 사이수: number): 점[] | null => {
  const [cx, cy] = [열 / 2, 줄 / 2];
  for (let 번 = 0; 번 < 20; 번 += 1) {
    const a = 2 + next(3);
    if (2 * a - 1 < 사이수) continue;
    const xs = 섞기(Array.from({ length: 2 * a - 1 }, (_, k) => cx - a + 1 + k), next).slice(0, 사이수).sort((p, q) => p - q);
    const ps: 점[] = [[cx - a, cy], ...xs.map((x): 점 => [x, cy - 1 - next(3)]), [cx + a, cy]];
    if (!꺾인곳없음(ps)) return ps;
  }
  return null;
};

const 대칭그림 = (선대칭인가: boolean, shape: 점[], 덧: Partial<SymmetryDrawVisual> = {}): SymmetryDrawVisual => ({
  kind: 'symmetry-draw',
  label: 선대칭인가 ? '선대칭도형의 반쪽' : '점대칭도형의 반쪽',
  mode: 선대칭인가 ? 'line' : 'point',
  cols: 열,
  rows: 줄,
  shape,
  names: 자음이름.slice(0, shape.length),
  ...(선대칭인가 ? { axisX: 열 / 2 } : { center: [열 / 2, 줄 / 2] as 점 }),
  ...덧,
});

const 대응 = (선대칭인가: boolean, p: 점): 점 => (선대칭인가 ? [열 - p[0], p[1]] : [열 - p[0], 줄 - p[1]]);
const 안인가 = (p: 점, cols = 열, rows = 줄) => p[0] >= 0 && p[0] <= cols && p[1] >= 0 && p[1] <= rows;

/** 대응점을 찾을 꼭짓점: 선대칭은 축 밖의 점, 점대칭은 양 끝을 뺀 사이의 점입니다. */
const 사이점 = (shape: 점[]) => shape.map((p, at) => ({ p, at })).slice(1, -1);

/** 고를 자리 넷(정답 하나와 실수 자리 셋)을 가·나·다·라로 이름 붙입니다. */
const 자리넷 = (
  정답: 점,
  실수: 점[],
  피할점: 점[],
  next: (n: number) => number,
  cols = 열,
  rows = 줄,
): { candidates: Array<{ at: 점; name: string }>; 정답이름: string } | null => {
  const 고른: 점[] = [];
  for (const p of 실수) {
    if (!안인가(p, cols, rows)) continue;
    if (같은점(p, 정답) || 고른.some((q) => 같은점(p, q)) || 피할점.some((q) => 같은점(p, q))) continue;
    // 고를 자리끼리 붙어 있으면 동그라미와 이름이 겹칩니다.
    고른.push(p);
    if (고른.length === 3) break;
  }
  if (고른.length < 3) return null;
  const 놓인 = 섞기([정답, ...고른], next);
  const candidates = 놓인.map((at, k) => ({ at, name: 가나다라[k] }));
  return { candidates, 정답이름: 가나다라[놓인.findIndex((p) => 같은점(p, 정답))] };
};

// ── 대응점을 어디에 찍어야 할까요 ────────────────────────────────────
const 대응점고르기 = (선대칭인가: boolean): G5Family => ({
  id: 'draw-image-point',
  make: (seed) => {
    const next = rand(seed);
    const shape = 선대칭인가 ? 선대칭반쪽(next, 2 + next(2)) : 점대칭반쪽(next, 1 + next(2));
    if (!shape) return null;
    const 고를것 = 사이점(shape);
    const { p, at } = 고를것[next(고를것.length)];
    const 이름 = 자음이름[at];
    const 정답 = 대응(선대칭인가, p);
    const 실수: 점[] = 선대칭인가
      ? [
          // 칸을 하나 더 세거나 덜 센 자리
          [정답[0] - 1, 정답[1]],
          // 대칭축에 수직이 아니게 비스듬히 간 자리
          [정답[0], 정답[1] + (next(2) ? 1 : -1)],
          [정답[0] + 1, 정답[1]],
          [정답[0], 정답[1] - 1],
          [정답[0], 정답[1] + 1],
          // 점대칭으로 돌린 자리
          [열 - p[0], 줄 - p[1]],
        ]
      : [
          // 점대칭을 그려야 하는데 세로선으로 뒤집은 자리(오개념 ④)
          [열 - p[0], p[1]],
          // 가로선으로 뒤집은 자리
          [p[0], 줄 - p[1]],
          // 중심을 지나 칸을 하나 더 세거나 덜 센 자리
          [정답[0], 정답[1] + 1],
          [정답[0] + 1, 정답[1]],
          [정답[0] - 1, 정답[1]],
          [정답[0], 정답[1] - 1],
        ];
    // 대칭의 중심 위에는 고를 자리를 두지 않습니다(중심과 겹쳐 보이지 않습니다).
    const 피할점: 점[] = [...shape, ...shape.map((q) => 대응(선대칭인가, q)), [열 / 2, 줄 / 2]];
    const 자리 = 자리넷(정답, 실수, 피할점, next);
    if (!자리) return null;
    const 이름말 = 선대칭인가 ? '선대칭도형' : '점대칭도형';
    const 거리 = p[0] - 열 / 2;
    const 중심까지 = 방향말(열 / 2 - p[0], 줄 / 2 - p[1]);
    return {
      prompt: `${이름말}의 반쪽을 그렸습니다. 나머지 반쪽을 그리려면 점 ${이름}의 대응점을 가, 나, 다, 라 중 어디에 찍어야 할까요?`,
      answer: 자리.정답이름,
      wrongs: 가나다라.filter((one) => one !== 자리.정답이름),
      tag: 'congruence',
      strategy: `${이름말}을 그릴 때 대응점 찍기`,
      hint: 선대칭인가
        ? `점 ${이름}에서 대칭축까지 수직으로 몇 칸인지 세어 보세요. 대칭축 반대쪽으로 그만큼 가면 됩니다.`
        : `점 ${이름}에서 대칭의 중심까지 어느 쪽으로 몇 칸 가는지 세어 보세요. 중심을 지나 그만큼 한 번 더 가면 됩니다.`,
      steps: 선대칭인가
        ? [
            `점 ${이름}에서 대칭축에 수직인 선을 그으면 대칭축까지 ${거리}칸입니다.`,
            `대칭축에서 반대쪽(왼쪽)으로 같은 ${거리}칸을 간 곳이 대응점입니다.`,
            `그러므로 ${자리.정답이름}에 찍어야 합니다.`,
          ]
        : [
            `점 ${이름}에서 대칭의 중심까지 ${중심까지} 갑니다.`,
            `중심에서 같은 방향으로 한 번 더 ${중심까지} 간 곳이 대응점입니다.`,
            `그러므로 ${자리.정답이름}에 찍어야 합니다.`,
          ],
      visual: 대칭그림(선대칭인가, shape, { candidates: 자리.candidates }),
      misconceptionTip: 선대칭인가
        ? '대응점은 대칭축과 수직인 같은 가로줄 위에 있습니다. 비스듬히 찍지 마세요.'
        : '점대칭도형은 접어서 뒤집는 것이 아니라 중심을 지나 반대쪽으로 갑니다. 선대칭처럼 좌우만 바꾸지 마세요.',
      selfCheck: 선대칭인가 ? '대칭축에서 두 점까지의 칸 수가 같나요?' : '점, 중심, 대응점이 한 직선 위에 있고 중심까지의 거리가 같나요?',
    };
  },
});

// ── 대응점은 대칭축(중심)에서 어느 쪽으로 몇 칸일까요 ─────────────────
