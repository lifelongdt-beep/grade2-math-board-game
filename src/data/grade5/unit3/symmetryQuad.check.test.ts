import { describe, expect, it } from 'vitest';
import { 각으로삼각형, 선대칭사각형, 선대칭짝, 점대칭사각형, 점대칭짝 } from './figures';

// 그림에 적은 각도와 실제로 그려지는 각이 같은지 잽니다.
//
// 대응각 문항은 "각 ㄱㄴㄷ이 110°"라고 적으면서 그림을 달지 않았습니다.
// 그림을 달면서, 정해 둔 모양을 쓰면 이번에는 그림과 글이 어긋납니다
// — 평행사변형은 늘 110.6°로 그려지는데 문제는 83°라고 적습니다.
// 그래서 각도에 맞추어 꼭짓점을 계산하는데, 그 계산이 맞는지를 그림이
// 그럴듯해 보이는 것으로 판단할 수는 없습니다. 실제로 재 봅니다.

const 잰각 = (점들: Array<[number, number]>, 자리: number) => {
  const 앞 = 점들[(자리 + 3) % 4];
  const 뒤 = 점들[(자리 + 1) % 4];
  const 가운데 = 점들[자리];
  const a: [number, number] = [앞[0] - 가운데[0], 앞[1] - 가운데[1]];
  const b: [number, number] = [뒤[0] - 가운데[0], 뒤[1] - 가운데[1]];
  const 내적 = a[0] * b[0] + a[1] * b[1];
  const 길이 = Math.hypot(...a) * Math.hypot(...b);
  return (Math.acos(내적 / 길이) * 180) / Math.PI;
};

const 쓰는각들 = Array.from({ length: 90 }, (_, i) => 50 + i).filter((one) => one !== 90);

describe('대칭 사각형은 적어 둔 각도 그대로 그려진다', () => {
  it('점대칭 사각형(평행사변형)의 그 자리 내각이 적어 둔 각도와 같습니다', () => {
    const 어긋남: string[] = [];
    for (const 각 of 쓰는각들) {
      for (const 자리 of [0, 1, 2, 3]) {
        const 잰것 = 잰각(점대칭사각형(자리, 각), 자리);
        if (Math.abs(잰것 - 각) > 0.5) {
          어긋남.push(`${자리}번 자리에 ${각}°라 적었는데 그림은 ${잰것.toFixed(1)}°`);
        }
      }
    }
    expect(어긋남.slice(0, 8)).toEqual([]);
  });

  it('선대칭 사각형(등변사다리꼴)의 그 자리 내각이 적어 둔 각도와 같습니다', () => {
    const 어긋남: string[] = [];
    for (const 각 of 쓰는각들) {
      for (const 자리 of [0, 1, 2, 3]) {
        const 잰것 = 잰각(선대칭사각형(자리, 각), 자리);
        if (Math.abs(잰것 - 각) > 0.5) {
          어긋남.push(`${자리}번 자리에 ${각}°라 적었는데 그림은 ${잰것.toFixed(1)}°`);
        }
      }
    }
    expect(어긋남.slice(0, 8)).toEqual([]);
  });

  it('대응각이라고 말한 자리의 내각이 실제로 같은 크기입니다', () => {
    // 대응각의 크기가 같다는 것이 이 문항이 묻는 전부입니다. 짝을
    // 잘못 가리키면 해설이 틀린 곳을 짚게 됩니다.
    const 어긋남: string[] = [];
    for (const 각 of 쓰는각들) {
      for (const 자리 of [0, 1, 2, 3]) {
        const 점 = 점대칭사각형(자리, 각);
        const 점짝 = 잰각(점, 점대칭짝(자리));
        if (Math.abs(점짝 - 각) > 0.5) {
          어긋남.push(`점대칭 ${자리}번(${각}°)의 짝 ${점대칭짝(자리)}번이 ${점짝.toFixed(1)}°`);
        }
        const 선 = 선대칭사각형(자리, 각);
        const 선짝 = 잰각(선, 선대칭짝(자리));
        if (Math.abs(선짝 - 각) > 0.5) {
          어긋남.push(`선대칭 ${자리}번(${각}°)의 짝 ${선대칭짝(자리)}번이 ${선짝.toFixed(1)}°`);
        }
      }
    }
    expect(어긋남.slice(0, 8)).toEqual([]);
  });

  it('점대칭 사각형은 정말 점대칭이고, 선대칭 사각형은 정말 선대칭입니다', () => {
    // 문제글이 '점대칭도형인 사각형'이라고 말하므로, 그림이 실제로
    // 그러해야 합니다. 아니면 그림이 오개념을 가르칩니다.
    const 어긋남: string[] = [];
    for (const 각 of 쓰는각들) {
      for (const 자리 of [0, 1, 2, 3]) {
        // 점대칭: 마주 보는 꼭짓점의 한가운데가 모두 같은 점입니다.
        const 점 = 점대칭사각형(자리, 각);
        const 가운데1 = [(점[0][0] + 점[2][0]) / 2, (점[0][1] + 점[2][1]) / 2];
        const 가운데2 = [(점[1][0] + 점[3][0]) / 2, (점[1][1] + 점[3][1]) / 2];
        if (Math.hypot(가운데1[0] - 가운데2[0], 가운데1[1] - 가운데2[1]) > 0.01) {
          어긋남.push(`점대칭 ${자리}번(${각}°)의 대칭의 중심이 하나가 아닙니다`);
        }
        // 선대칭: 세로 축(x=0)에 대해 0↔1, 2↔3이 거울상입니다.
        const 선 = 선대칭사각형(자리, 각);
        for (const [왼, 오] of [[0, 1], [3, 2]] as const) {
          if (Math.abs(선[왼][0] + 선[오][0]) > 0.01 || Math.abs(선[왼][1] - 선[오][1]) > 0.01) {
            어긋남.push(`선대칭 ${자리}번(${각}°)에서 ${왼}번과 ${오}번이 세로 축을 사이에 두고 겹치지 않습니다`);
          }
        }
      }
    }
    expect(어긋남.slice(0, 8)).toEqual([]);
  });

  it('대응각은 저 자신이 아닌 다른 꼭짓점입니다', () => {
    for (const 자리 of [0, 1, 2, 3]) {
      expect(점대칭짝(자리)).not.toBe(자리);
      expect(선대칭짝(자리)).not.toBe(자리);
      expect([0, 1, 2, 3]).toContain(점대칭짝(자리));
      expect([0, 1, 2, 3]).toContain(선대칭짝(자리));
    }
  });
});

// ── 정육각형의 대응점 ────────────────────────────────────────────────
// '세 칸 건너뛴 점'은 점대칭의 대응입니다. 선대칭에도 그대로 쓰던 것을
// 바로잡았으므로, 다시 섞이지 않게 실제 도형으로 재어 둡니다.

const 정육각형 = Array.from({ length: 6 }, (_, k): [number, number] => {
  const t = (Math.PI * 2 * k) / 6 - Math.PI / 2;
  return [Math.cos(t), Math.sin(t)];
});

const 같은자리 = (a: [number, number], b: [number, number]) =>
  Math.hypot(a[0] - b[0], a[1] - b[1]) < 1e-6;

describe('정육각형의 대응점', () => {
  it('점대칭(중심에서 반 바퀴)에서는 세 칸 건너가 맞습니다', () => {
    for (let 자리 = 0; 자리 < 6; 자리 += 1) {
      const [x, y] = 정육각형[자리];
      const 돌린것: [number, number] = [-x, -y];
      expect(같은자리(돌린것, 정육각형[(자리 + 3) % 6])).toBe(true);
    }
  });

  it('선대칭(세로 축)에서는 ㄴ↔ㅂ, ㄷ↔ㅁ이고 ㄱ·ㄹ은 축 위에 있습니다', () => {
    const 비춘짝 = (자리: number) => {
      const [x, y] = 정육각형[자리];
      return 정육각형.findIndex((p) => 같은자리([-x, y], p));
    };
    expect(비춘짝(1)).toBe(5);
    expect(비춘짝(5)).toBe(1);
    expect(비춘짝(2)).toBe(4);
    expect(비춘짝(4)).toBe(2);
    // 축 위의 두 꼭짓점은 저 자신입니다. 그래서 문항에서 묻지 않습니다.
    expect(비춘짝(0)).toBe(0);
    expect(비춘짝(3)).toBe(3);
  });

  it('어떤 대칭축으로 접어도 여섯 꼭짓점이 한꺼번에 세 칸씩 옮겨 가지 않습니다', () => {
    // 이것이 예전 문항이 가르치던 것이었습니다. 정육각형의 대칭축은
    // 30°마다 여섯 개입니다. 하나씩 접어 봅니다.
    for (let 축 = 0; 축 < 6; 축 += 1) {
      const th = (Math.PI * 축) / 6;
      const 짝들 = 정육각형.map(([x, y]) => {
        const 비춘것: [number, number] = [
          Math.cos(2 * th) * x + Math.sin(2 * th) * y,
          Math.sin(2 * th) * x - Math.cos(2 * th) * y,
        ];
        return 정육각형.findIndex((p) => 같은자리(비춘것, p));
      });
      const 모두세칸 = 짝들.every((to, from) => to === (from + 3) % 6);
      expect(모두세칸, `축 ${축 * 30}°에서 세 칸 건너가 되어 버렸습니다`).toBe(false);
    }
  });
});

// ── 대응변 ───────────────────────────────────────────────────────────
// 대응변의 길이가 같다는 것이 그 문항이 묻는 전부입니다. 짝을 잘못
// 가리키면 해설이 틀린 변을 짚습니다.

const 변길이 = (점들: Array<[number, number]>, 자리: number) => {
  const a = 점들[자리];
  const b = 점들[(자리 + 1) % 4];
  return Math.hypot(a[0] - b[0], a[1] - b[1]);
};

describe('대응변은 길이가 같은 변을 가리킨다', () => {
  it('점대칭 사각형에서 마주 보는 변끼리 길이가 같습니다', () => {
    for (let 각 = 55; 각 < 85; 각 += 1) {
      const 점 = 점대칭사각형(0, 각);
      for (let 자리 = 0; 자리 < 4; 자리 += 1) {
        expect(Math.abs(변길이(점, 자리) - 변길이(점, (자리 + 2) % 4))).toBeLessThan(0.001);
      }
    }
  });

  it('선대칭 사각형에서 두 빗변(1번과 3번)의 길이가 같습니다', () => {
    for (let 각 = 55; 각 < 85; 각 += 1) {
      const 점 = 선대칭사각형(0, 각);
      expect(Math.abs(변길이(점, 1) - 변길이(점, 3))).toBeLessThan(0.001);
    }
  });

  it('선대칭 사각형의 윗변과 아랫변은 서로 짝이 아닙니다', () => {
    // 그래서 문항에서 묻지 않습니다. 길이가 다르므로, 물었다면
    // '대응변의 길이도 같다'는 해설이 틀린 말이 됩니다.
    for (let 각 = 55; 각 < 85; 각 += 1) {
      const 점 = 선대칭사각형(0, 각);
      expect(Math.abs(변길이(점, 0) - 변길이(점, 2))).toBeGreaterThan(0.05);
    }
  });
});

describe('합동인 두 삼각형은 적어 둔 각도 그대로 그려진다', () => {
  it('세 각이 모두 적어 둔 값과 같습니다', () => {
    const 잰삼각형각 = (점들: Array<[number, number]>, 자리: number) => {
      const 앞 = 점들[(자리 + 2) % 3];
      const 뒤 = 점들[(자리 + 1) % 3];
      const 가운데 = 점들[자리];
      const a: [number, number] = [앞[0] - 가운데[0], 앞[1] - 가운데[1]];
      const b: [number, number] = [뒤[0] - 가운데[0], 뒤[1] - 가운데[1]];
      const 내적 = a[0] * b[0] + a[1] * b[1];
      return (Math.acos(내적 / (Math.hypot(...a) * Math.hypot(...b))) * 180) / Math.PI;
    };

    const 어긋남: string[] = [];
    // 문항이 뽑는 범위 그대로 훑습니다(각1, 각2는 40~89, 나머지가 셋째).
    for (let 각1 = 40; 각1 < 90; 각1 += 1) {
      for (let 각2 = 40; 각2 < 90; 각2 += 1) {
        const 각3 = 180 - 각1 - 각2;
        if (각3 <= 15 || 각3 >= 140) continue;
        const 점 = 각으로삼각형([각1, 각2, 각3]);
        for (const [자리, 참값] of [[0, 각1], [1, 각2], [2, 각3]] as const) {
          if (Math.abs(잰삼각형각(점, 자리) - 참값) > 0.5) {
            어긋남.push(`${각1},${각2},${각3}의 ${자리}번이 ${잰삼각형각(점, 자리).toFixed(1)}°`);
          }
        }
      }
    }
    expect(어긋남.slice(0, 8)).toEqual([]);
  });
});
