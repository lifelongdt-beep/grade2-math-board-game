import { describe, expect, it } from 'vitest';
import { lessons } from './curriculum';
import { generateQuestions } from './questionFactory';
import type { Difficulty, Question } from '../types';

// 한 차시-수준의 서른 자리에서 똑같은 문제가 몇 칸을 차지해도 되는지입니다.
// 여섯에 하나까지입니다.
//
// 이 수를 정한 까닭입니다. 아이는 문제를 읽고 푸는 것이 아니라 "아까
// 그거"를 누릅니다. 같은 문제가 서른 칸 가운데 열 칸이면 그 차시는
// 사실상 세 문제짜리이고, 아이는 세 문제를 외운 뒤 나머지 스물일곱
// 칸을 생각 없이 넘깁니다. 문항 수가 많아 보이는 것은 착각입니다.
//
// '똑같은 문제'는 아이가 화면에서 보는 것 전부로 셉니다 — 문제글만이
// 아니라 그림과 답과 보기까지입니다. 문제글만 보고 세면 두 가지를
// 놓칩니다.
//
//   - 문제글이 같아도 그림이 다르면 아이가 하는 일은 다릅니다.
//     '삼각형은 어느 것일까요?'는 그림으로 묻는 문항이라 글이 같을
//     수밖에 없습니다. 이것을 겹친 것으로 세면, 고칠 것이 없는 자리를
//     고치라고 하게 됩니다.
//   - 거꾸로, 문제글이 같으면서 그림과 답까지 같은 자리가 있었습니다.
//     '무늬에서 ?에 들어갈 모양을 고르세요'는 일곱 자리가 그림도 답도
//     하나였습니다. 글만 세도 걸리기는 하지만, 얼마나 나쁜지는
//     드러나지 않습니다.
//
// 자리를 채울 문항이 모자라면 수를 올리지 말고 그 차시에 문항 모양을
// 더 써야 합니다. 수를 올리면 이 시험은 통과하지만 아이가 보는 것은
// 그대로입니다.
const 한문제에게줄수있는칸 = 5;

const 수준들: Difficulty[] = ['하', '중', '상'];

// 아이가 화면에서 보는 것입니다.
//
// 보기는 순서를 맞추어 놓고 견줍니다. 보기의 차례는 자리마다 섞이므로,
// 섞인 차례까지 넣고 세면 똑같은 문제도 모두 다른 문제로 세어집니다.
// 실제로 그렇게 세었다가 이 시험이 헛돌았습니다 — 그림도 답도 보기도
// 같고 버튼 차례만 다른 문제가 한 차시에 일곱 번 나오는데 시험은
// 통과했습니다. 아이에게 버튼 차례가 바뀐 것은 다른 문제가 아닙니다.
const 아이가보는것 = (문항: Question) =>
  JSON.stringify([문항.prompt, 문항.answer, [...문항.choices].sort(), 문항.visual ?? null]);

describe('같은 문제가 한 차시를 덮지 않는지', () => {
  it(`어느 차시-수준에서도 같은 문제가 ${한문제에게줄수있는칸}칸을 넘지 않습니다`, () => {
    const 넘은것: string[] = [];

    for (const 차시 of lessons) {
      for (const 수준 of 수준들) {
        const 문항들 = generateQuestions(차시, 수준);
        const 센것 = new Map<string, { 칸수: number; 글: string }>();
        for (const 문항 of 문항들) {
          const 열쇠 = 아이가보는것(문항);
          const 이미 = 센것.get(열쇠);
          if (이미) 이미.칸수 += 1;
          else 센것.set(열쇠, { 칸수: 1, 글: 문항.prompt });
        }
        for (const { 칸수, 글 } of 센것.values()) {
          if (칸수 > 한문제에게줄수있는칸) {
            넘은것.push(`${차시.id} ${수준}  ${칸수}칸: ${글.slice(0, 50)}`);
          }
        }
      }
    }

    expect(넘은것, `\n${넘은것.join('\n')}\n`).toEqual([]);
  });
});
