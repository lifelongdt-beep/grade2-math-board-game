/** 단원 도입 차시인지(2-2 2단원은 1차시가 구구단 놀이라 2차시가 도입입니다) */
export const 도입차시인가 = (lesson: Lesson) => lesson.title === '단원 도입';

const 놀이차시 = new Set(['구구단, 몬스터를 막아라!']);

/** 단원 도입 차시가 복습할 앞 단원의 차시들. 표에 없으면 null입니다. */
export const 도입복습차시 = (lesson: Lesson): Lesson[] | null => {
  if (!도입차시인가(lesson)) return null;
  const 앞 = 도입선수단원[`${lesson.semester}-${lesson.unitNo}`];
  if (!앞) return null;
  const 차시들 = 앞.flatMap((키) => {
    const [학년, 학기, 단원] = 키.split('-');
    const unit = 모든단원.find((u) => u.lessons[0]?.semester === `${학년}-${학기}` && u.lessons[0]?.unitNo === Number(단원));
    return (unit?.lessons ?? []).filter((l) => !도입차시인가(l) && !놀이차시.has(l.title));
  });
  return 차시들.length > 0 ? 차시들 : null;
};
