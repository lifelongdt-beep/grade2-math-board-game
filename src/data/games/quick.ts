// 놀이는 오락실 게임처럼 몇 초 안에 읽고 바로 눌러야 신납니다. 차시 문항을
// 가져다 쓰면 이미 풀어 본 긴 문제가 다시 나와 지겹습니다. 그래서 놀이 문항은
// 단원마다 새로 짓습니다 — 그 단원의 핵심 개념을 묻는 한 줄 질문이거나 한 번에
// 끝나는 단순 계산입니다('7 + 5 = ?', '직각은 몇 도?', '↑을 시계 방향으로
// 90° 돌리면?').
//
// 수는 씨앗으로 고르므로 판마다 다른 문제가 나오고, 하·중·상은 수의 크기만
// 조금씩 키웁니다. 보기는 늘 정답 하나와 아이들이 흔히 고르는 오답으로 짭니다.
