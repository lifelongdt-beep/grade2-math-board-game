const 단원열쇠 = (lesson: Pick<Lesson, 'semester' | 'unitNo'>) => `${lesson.semester}-u${lesson.unitNo}`;

export const 단순문항있나 = (lesson: Pick<Lesson, 'semester' | 'unitNo'>) => 단원열쇠(lesson) in 단원표;

const 수준값: Record<Difficulty, number> = { 하: 0, 중: 1, 상: 2 };

/**
 * 놀이 차시의 단순 문항을 새로 짓습니다. 같은 글과 같은 보기가 겹치지 않게 모으고,
 * 보기가 셋보다 적은 문항은 버립니다.
 */
export const 단순문항 = (game: Lesson, difficulty: Difficulty, seed: number, 수: number): Question[] => {
  const 표 = 단원표[단원열쇠(game)];
  if (!표) return [];
  const r = 씨앗난수(seed * 7919 + 수준값[difficulty] * 104729 + game.unitNo * 31);
  const 본 = new Set<string>();
  const out: Question[] = [];
  for (let 시도 = 0; out.length < 수 && 시도 < 수 * 40; 시도 += 1) {
    const 만들기 = 표.생성들[Math.floor(r() * 표.생성들.length)];
    const 문 = 만들기(r, 수준값[difficulty]);
    if (!문) continue;
    const 보기 = [...new Set([문.a, ...문.w.filter((x) => x !== 문.a)])].slice(0, 4);
    if (보기.length < 3) continue;
    const 열쇠 = `${문.q}|${[...보기].sort().join('|')}`;
    if (본.has(열쇠)) continue;
    본.add(열쇠);
    const 섞인 = 섞기(r, 보기);
    out.push({
      id: `${game.id}-${difficulty}-${out.length + 1}`,
      lessonId: game.id,
      difficulty,
      prompt: 문.q,
      basePrompt: 문.q,
      thinkingLevel: 0,
      choices: 섞인,
      answerIndex: 섞인.indexOf(문.a),
      answer: 문.a,
      explanation: 문.why,
      misconception: 표.핵심,
      type: 표.tag,
      strategy: '핵심 개념 빠르게 떠올리기',
      support: {
        studentConcept: 표.핵심,
        studentHint: 표.핵심,
        coreConcept: 표.핵심,
        readStrategy: '짧게 읽고 바로 떠올려요.',
        steps: [문.why],
        misconceptionTip: '',
        textbookConnection: game.title,
        selfCheck: '답을 문제에 넣어 맞는지 확인해요.',
      },
    });
  }
  return out;
};
