const 씨앗난수 = (seed: number): 난수 => {
  let s = (seed >>> 0) || 1;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
};
const 정수 = (r: 난수, lo: number, hi: number) => lo + Math.floor(r() * (hi - lo + 1));
const 하나 = <T,>(r:난수, xs: readonly T[]): T => xs[Math.floor(r() * xs.length)];
const 섞기 = <T,>(r:난수, xs: readonly T[]): T[] => {
  const out = [...xs];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(r() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
};
const 몇개 = <T,>(r:난수, xs: readonly T[], n: number): T[] => 섞기(r, xs).slice(0, n);
const 최대공약수 = (a: number, b: number): number => (b === 0 ? Math.abs(a) : 최대공약수(b, a % b));
const 최소공배수 = (a: number, b: number) => (a / 최대공약수(a, b)) * b;
/** 소수 계산의 0.30000000004 같은 꼬리를 떼고 글로 씁니다. */
const 소 = (x: number) => String(Number(x.toFixed(6)));

/** 수를 소리 내어 읽을 때 끝에 받침이 있는지입니다(일·삼·육·칠·팔·영, 십·백·천·만). */
const 받침수 = (n: number | string): boolean => {
  // 분수는 '6분의 21'처럼 분자를 마지막에 읽습니다.
  const 분수 = /(\d+)\/\d+$/.exec(String(n));
  const 글 = 분수 ? 분수[1] : String(n);
  const 끝 = 글[글.length - 1];
  if (!/\d/.test(끝)) return /[ㄱ-ㅎ가-힣]/.test(끝) ? (끝.charCodeAt(0) - 0xac00) % 28 !== 0 : false;
  if (/^\d+$/.test(글) && Number(글) !== 0 && 끝 === '0') return true;
  return ['0', '1', '3', '6', '7', '8'].includes(끝);
};
const 을 = (n: number | string) => `${n}${받침수(n) ? '을' : '를'}`;
const 이 = (n: number | string) => `${n}${받침수(n) ? '이' : '가'}`;
const 과 = (n: number | string) => `${n}${받침수(n) ? '과' : '와'}`;
const 은 = (n: number | string) => `${n}${받침수(n) ? '은' : '는'}`;
/** '로/으로'는 받침이 없거나 ㄹ 받침(일·칠·팔)이면 '로'입니다. */
const 로 = (n: number | string) => {
  const 끝 = String(n).slice(-1);
  const ㄹ = ['1', '7', '8'].includes(끝) && !(/^\d+$/.test(String(n)) && Number(n) !== 0 && 끝 === '0');
  return `${n}${!받침수(n) || ㄹ ? '로' : '으로'}`;
};

/** 정답 둘레의 흔한 오답(하나 크게·작게, 자리 바꿈)입니다. 음수와 정답은 뺍니다. */
const 근처 = (a: number, ...d: number[]) => d.map((x) => a + x).filter((x) => x >= 0 && x !== a);
const 수문제 = (q: string, a: number, w: number[], why: string, 꼬리 = ''): 한문제 =>
  ({ q, a: `${소(a)}${꼬리}`, w: w.map((x) => `${소(x)}${꼬리}`), why });
const 사실 = (q: string, a: string, w: string[], why: string): 한문제 => ({ q, a, w, why });
/** 사실 묶음에서 하나를 고릅니다. */
const 사실들 = (list: 한문제[]): 생성 => (r) => 하나(r, list);

// 가장 큰(작은) 것 고르기: 같은 질문이라도 보기가 달라 다른 문제가 됩니다.
const 가장 = (q: string, 고른: number[], 큰: boolean, why: string, 글 = (x: number) => 소(x)): 한문제 => {
  const 답 = 큰 ? Math.max(...고른) : Math.min(...고른);
  return { q, a: 글(답), w: 고른.filter((x) => x !== 답).map(글), why };
};

const 고유어 = (n: number): string => {
  const 열 = ['', '열', '스물', '서른', '마흔', '쉰', '예순', '일흔', '여든', '아흔'];
  const 낱 = ['', '하나', '둘', '셋', '넷', '다섯', '여섯', '일곱', '여덟', '아홉'];
  return `${열[Math.floor(n / 10)]}${낱[n % 10]}`;
};

// 화살표 모양 돌리기·뒤집기입니다(시계 방향 차례).
const 화살표 = ['↑', '↗', '→', '↘', '↓', '↙', '←', '↖'];
const 돌리기 = (x: string, 시계칸: number) => 화살표[(화살표.indexOf(x) + 시계칸 + 16) % 8];
// 왼쪽·오른쪽으로 뒤집으면 좌우가, 위쪽·아래쪽으로 뒤집으면 위아래가 바뀝니다.
const 좌우뒤집기 = (x: string) => 화살표[(8 - 화살표.indexOf(x)) % 8];
const 위아래뒤집기 = (x: string) => 화살표[(12 - 화살표.indexOf(x)) % 8];

