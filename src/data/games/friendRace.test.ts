import { describe, expect, it } from 'vitest';
import { 새친구판, 순위매기기, 판넘기기, 판점수 } from './friendRace';

describe('친구와 겨루는 판', () => {
  const ids = [1, 2, 3];

  it('아무도 결승에 닿지 않으면 판이 그대로입니다', () => {
    const 판 = 새친구판();
    expect(판넘기기(판, ids, { 1: 4, 2: 2 }, 5)).toBe(판);
  });

  it('먼저 결승 점수를 낸 아이가 판을 이기고 모두 0점에서 다시 시작합니다', () => {
    const 판 = 판넘기기(새친구판(), ids, { 1: 5, 2: 3, 3: 0 }, 5);
    expect(판.판).toBe(1);
    expect(판.승자).toEqual([1]);
    expect(판.승).toEqual({ 1: 1, 2: 0, 3: 0 });
    expect(ids.map((id) => 판점수(판, { 1: 5, 2: 3, 3: 0 }, id))).toEqual([0, 0, 0]);
    // 다음 판은 새로 맞힌 개수로 겨룹니다. 앞 판에서 진 아이도 이길 수 있습니다.
    const 다음 = 판넘기기(판, ids, { 1: 6, 2: 8, 3: 1 }, 5);
    expect(다음.승자).toEqual([2]);
    expect(다음.승).toEqual({ 1: 1, 2: 1, 3: 0 });
  });

  it('같이 결승에 닿으면 둘 다 이깁니다', () => {
    const 판 = 판넘기기(새친구판(), ids, { 1: 5, 2: 5, 3: 1 }, 5);
    expect(판.승자).toEqual([1, 2]);
  });

  it('순위는 이긴 판, 이번 판 점수, 맞힌 개수 차례로 정하고 같으면 같은 등수입니다', () => {
    const 판 = 판넘기기(새친구판(), ids, { 1: 5, 2: 3, 3: 2 }, 5);
    expect(순위매기기(판, ids, { 1: 5, 2: 4, 3: 4 })).toEqual({ 1: 1, 2: 2, 3: 3 });
    expect(순위매기기(판, ids, { 1: 5, 2: 6, 3: 5 })).toEqual({ 1: 1, 2: 2, 3: 3 });
    expect(순위매기기(새친구판(), ids, { 1: 2, 2: 2, 3: 1 })).toEqual({ 1: 1, 2: 1, 3: 3 });
  });
});
